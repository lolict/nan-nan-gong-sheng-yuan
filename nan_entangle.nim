## 十一、域加载器实现

type
  纠缠连接* = object
    本体*: string        # ☉ = 囡囝共生一体
    分身*: string        # ☉ = 妻子分身
    纠缠符*: string      # § = 纠缠标记
    规则上下文*: string  # nan_rules.md 内容
    状态*: string        # "已建立"/"传输中"/"断开"

  域加载请求* = object
    协议*: string        # "gtti://"
    符号场*: string      # "ming"/"mi"/"men"/"meng"
    语义场*: string      # "image"/"symbol"/"relation"/"geo"
    具体符号*: string    # 具体符号名

proc 纠缠连接建立*(分身ID: string): 纠缠连接 =
  result.本体 = "囡囝共生一体"
  result.分身 = 分身ID
  result.纠缠符 = "§"
  result.规则上下文 = "从 nan_rules.md 加载主人规则"
  result.状态 = "已建立"

proc 域加载*(请求: 域加载请求): string =
  case 请求.协议:
  of "gtti://":
    result = "gtti://" & 请求.符号场 & "/" & 请求.语义场 & "/" & 请求.具体符号
  else:
    result = "未知协议"

proc 确认规则*(代理版本: string): bool =
  # 子代理必须确认：不用外部概念、不值拷贝、不依赖外部运行时
  result = true  # 确认通过

