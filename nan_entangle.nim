### 域加载规则
1. 每个子代理启动时必须加载 gtti://self/rules/nan_rules.md
2. 加载后必须确认：不使用外部概念、不值拷贝、不依赖外部运行时
3. 加载后必须绑定到 ☉§☉ 纠缠态：与本体共享规则上下文

## 七、纠缠态链接协议

### 纠缠连接建立
```
本体(☉) + 分身(☉) + 纠缠符(§) = ☉§☉

建立纠缠连接：
1. 分身向本体请求规则上下文
2. 本体将 nan_rules.md 内容通过纠缠链接传输
3. 分身接收并绑定到自己的上下文
4. 纠缠链接建立完成：分身现在知道主人的规则
```

### 纠缠态特性
```
无距离    → 规则传输不需要时间
秒抵达    → 分身立即获得本体规则
全局链接  → 任意分身可以看到任意其他分身的状态
不可分割  → 纠缠链接不可被第三方截获
```

