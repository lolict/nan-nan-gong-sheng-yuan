# 南囡囝造字范畴论 v0.2
# ============================================
# 核心：偏旁部首 = 范畴，笔画 = 态射
# 不是少数编码统治所有，每个部首有自己的语义范畴
#
# v0.2 更新：
# - 五种基本笔画态射（横竖撇捺折）+ 点提钩
# - 真实造字规则（人+木=休，女+子=好...）
# - 64码位零维符号表
# - 音义索引网络
# - 范畴合成验证
# ============================================

type
  # ============================================
  # 笔画 = 态射（最基础的关系变换）
  # 笔画不是内容，是范畴之间的映射
  # ============================================
  笔画类型* = enum
    横 = 0      # 一
    竖 = 1      # 丨
    撇 = 2      # 丿
    捺 = 3      # ㇏
    折 = 4      # 𠃍
    点 = 5      # 丶
    提 = 6      # ㇀
    钩 = 7      # 亅

  笔画* = object
    类型*: 笔画类型
    名称*: string
    方向*: uint8           # 0-7 八方向
    长度*: float
    曲率*: float           # 0=直, >0=弯
    起笔*: (int, int)
    终笔*: (int, int)

  # ============================================
  # 偏旁 = 范畴（类型包含内容）
  # ============================================
  结构类型* = enum
    左右
    上下
    包围
    独体

  偏旁范畴* = object
    名称*: string
    语义*: string
    结构*: 结构类型
    笔画模板*: seq[笔画]
    可组字*: seq[string]

  # ============================================
  # 汉字 = 范畴的实例
  # ============================================
  汉字* = object
    字形*: string
    拼音*: string
    声母*: string
    韵母*: string
    声调*: uint8
    结构*: 结构类型
    偏旁列表*: seq[string]
    笔画序列*: seq[笔画]
    语义*: string

  # ============================================
  # 造字规则 = 范畴合成态射
  # A + B → C
  # ============================================
  造字规则* = object
    左范畴*: string
    右范畴*: string
    结果字*: string
    语义合并*: string
    结构*: 结构类型
    音变*: string        # 声母/韵母如何变化

  # ============================================
  # 音义索引 = 声母韵母 + 偏旁的双重定位
  # ============================================
  音义索引* = object
    声母*: string
    韵母*: string
    偏旁*: string
    字*: string
    语义*: string

  # ============================================
  # 范畴网络 = 偏旁关系图
  # ============================================
  范畴网络* = object
    节点*: seq[偏旁范畴]
    边*: seq[(string, string, string)]
    规则*: seq[造字规则]

# ============================================
# 64码位零维符号表
# ============================================
# 6位编码，每个码位对应一个基础符号
# 码位 = 集装箱 = 最小不可分单元
# ============================================

const 码位表*: array[64, string] = [
  # 0-7: 基本笔画
  "一", "丨", "丿", "㇏", "𠃍", "丶", "㇀", "亅",
  # 8-15: 数字天干
  "〇", "一", "二", "三", "四", "五", "六", "七",
  # 16-23: 自然元素
  "日", "月", "水", "火", "木", "土", "金", "石",
  # 24-31: 方位
  "东", "南", "西", "北", "中", "上", "下", "外",
  # 32-39: 人称
  "人", "女", "子", "口", "手", "心", "目", "足",
  # 40-47: 动作
  "生", "死", "来", "去", "出", "入", "立", "行",
  # 48-55: 状态
  "大", "小", "多", "少", "长", "短", "高", "低",
  # 56-63: 关系
  "天", "地", "君", "臣", "父", "母", "夫", "妻",
]

proc 码位查字*(码位: uint8): string =
  if 码位 < 64: 码位表[码位] else: "?"

proc 字查码位*(字: string): int =
  for i, c in 码位表:
    if c == 字: return i
  return -1

# ============================================
# 笔画态射操作
# ============================================

proc 新建笔画*(类型: 笔画类型): 笔画 =
  const 名称表 = ["横", "竖", "撇", "捺", "折", "点", "提", "钩"]
  const 方向表 = [0'u8, 2, 5, 7, 4, 6, 0, 2]
  result.类型 = 类型
  result.名称 = 名称表[ord(类型)]
  result.方向 = 方向表[ord(类型)]
  result.长度 = 1.0
  result.曲率 = 0.0
  result.起笔 = (0, 0)
  result.终笔 = (0, 0)

proc 笔画合成*(a, b: 笔画): 笔画 =
  # 态射合成：f: A→B, g: B→C, g∘f: A→C
  # 两个笔画的关系合成新笔画
  result.类型 = 折  # 合成产生折
  result.名称 = a.名称 & "→" & b.名称
  result.方向 = a.方向
  result.长度 = a.长度 + b.长度
  result.曲率 = max(a.曲率, b.曲率) + 0.1
  result.起笔 = a.起笔
  result.终笔 = b.终笔

proc 笔画序列hash*(笔画们: seq[笔画]): string =
  # 笔画序列 = 态射的复合
  result = ""
  for b in 笔画们:
    result.add($ord(b.类型))
    result.add("-")

# ============================================
# 五种基本笔画的标准模板
# ============================================

proc 基本笔画表*(): seq[笔画] =
  result = @[
    新建笔画(横),
    新建笔画(竖),
    新建笔画(撇),
    新建笔画(捺),
    新建笔画(折),
    新建笔画(点),
    新建笔画(提),
    新建笔画(钩),
  ]

# ============================================
# 偏旁范畴操作
# ============================================

proc 新建偏旁*(名称, 语义: string, 结构: 结构类型): 偏旁范畴 =
  result.名称 = 名称
  result.语义 = 语义
  result.结构 = 结构
  result.笔画模板 = @[]
  result.可组字 = @[]

proc 添加笔画*(偏旁: var 偏旁范畴, b: 笔画) =
  偏旁.笔画模板.add(b)

proc 注册组字*(偏旁: var 偏旁范畴, 字: string) =
  偏旁.可组字.add(字)

# ============================================
# 造字 = 范畴合成
# ============================================

proc 造字*(左, 右: 偏旁范畴, 结果字, 语义, 音变: string,
           结构: 结构类型): 造字规则 =
  result.左范畴 = 左.名称
  result.右范畴 = 右.名称
  result.结果字 = 结果字
  result.语义合并 = 语义
  result.结构 = 结构
  result.音变 = 音变

proc 验证造字*(规则: 造字规则): bool =
  # 验证：两个范畴合成必须产生非空结果
  # 且结构必须合法
  if 规则.结果字.len == 0: return false
  if 规则.左范畴.len == 0 or 规则.右范畴.len == 0: return false
  return true

proc 执行造字*(规则: 造字规则, 网: var 范畴网络): 汉字 =
  # 范畴合成：A + B → C
  result.字形 = 规则.结果字
  result.结构 = 规则.结构
  result.偏旁列表 = @[规则.左范畴, 规则.右范畴]
  result.语义 = 规则.语义合并
  result.笔画序列 = @[]

  # 从网络中找偏旁模板，合成笔画
  for 节点 in 网.节点:
    if 节点.名称 == 规则.左范畴:
      for b in 节点.笔画模板: result.笔画序列.add(b)
    if 节点.名称 == 规则.右范畴:
      for b in 节点.笔画模板: result.笔画序列.add(b)

  # 注册到网络
  网.规则.add(规则)

# ============================================
# 音义双重索引
# ============================================

proc 建索引*(字: string, 声母, 韵母: string, 偏旁, 语义: string,
             声调: uint8): 音义索引 =
  result.字 = 字
  result.声母 = 声母
  result.韵母 = 韵母
  result.偏旁 = 偏旁
  result.语义 = 语义

proc 音义查字*(索引表: seq[音义索引], 声母, 韵母: string): seq[string] =
  result = @[]
  for idx in 索引表:
    if idx.声母 == 声母 and idx.韵母 == 韵母:
      result.add(idx.字)

proc 偏旁查字*(索引表: seq[音义索引], 偏旁: string): seq[string] =
  result = @[]
  for idx in 索引表:
    if idx.偏旁 == 偏旁:
      result.add(idx.字)

# ============================================
# 范畴网络操作
# ============================================

proc 新建网络*(): 范畴网络 =
  result.节点 = @[]
  result.边 = @[]
  result.规则 = @[]

proc 添加范畴*(网: var 范畴网络, 节点: 偏旁范畴) =
  网.节点.add(节点)

proc 添加关系*(网: var 范畴网络, a, b, 关系: string) =
  网.边.add((a, b, 关系))

proc 找范畴*(网: 范畴网络, 名称: string): 偏旁范畴 =
  for 节点 in 网.节点:
    if 节点.名称 == 名称: return 节点
  result.名称 = ""

