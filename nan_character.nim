# 南囡囝造字范畴论 v0.1
# ============================================
# 核心：偏旁部首 = 范畴，笔画 = 态射
# 不是少数编码统治所有，每个部首有自己的语义范畴
# ============================================

type
  # ============================================
  # 笔画 = 态射（最基础的变换）
  # 笔画不是内容，是关系
  # ============================================
  笔画* = object
    名称*: string          # 横/竖/撇/捺/折
    方向*: uint8           # 0-7 八方向
    起笔*: (int, int)     # 相对坐标
    终笔*: (int, int)
    长度*: float           # 笔画长度
    曲率*: float           # 0=直, >0=弯

  # ============================================
  # 偏旁 = 范畴（类型）
  # 偏旁包含一组字
  # ============================================
  偏旁范畴* = object
    名称*: string              # "单人旁"、"绞丝旁"
    语义*: string              # 语义范畴："与人"、"与丝"
    结构*: string              # 左右/上下/包围/独体
    可组字*: seq[string]       # 能组哪些字
    子范畴*: seq[string]       # 下级偏旁

  # ============================================
  # 汉字 = 范畴的实例
  # 汉字由偏旁+笔画组合
  # ============================================
  汉字* = object
    字形*: string              # 字本身
    拼音*: string              # 读音
    声母*: string              # zh/ch/sh
    韵母*: string              # ang/eng/ing
    声调*: uint8               # 1-4
    结构*: string              # 左右/上下/包围/独体
    偏旁列表*: seq[string]     # 包含哪些偏旁
    笔画序列*: seq[笔画]        # 笔画顺序
    语义*: string              # 字义

  # ============================================
  # 范畴串联 = 造字
  # 偏旁A + 偏旁B = 新字
  # ============================================
  造字规则* = object
    左范畴*: string           # 左边偏旁
    右范畴*: string           # 右边偏旁
    结果字*: string           # 组成的字
    语义合并*: string         # 语义如何合并

  # ============================================
  # 拼音范畴 = 声母韵母索引
  # ============================================
  声母范畴* = object
    字母*: string             # zh/ch/sh/b/p/m/f
    音值*: string            # 国际音标
    可组字*: seq[string]

  韵母范畴* = object
    字母*: string             # ang/eng/ing/ong
    音值*: string
    可组字*: seq[string]

  # ============================================
  # 范畴网络 = 所有偏旁的关系图
  # ============================================
  范畴网络* = object
    节点*: seq[偏旁范畴]
    边*: seq[(string, string, string)]  # (偏旁A, 偏旁B, 关系)

# ============================================
# 笔画态射操作
# ============================================

proc 新建笔画*(名称: string, 方向: uint8): 笔画 =
  result.名称 = 名称
  result.方向 = 方向
  result.起笔 = (0, 0)
  result.曲率 = 0.0

proc 笔画合成*(a, b: 笔画): 笔画 =
  # 两个笔画合成一个新笔画
  result.名称 = a.名称 & "+" & b.名称
  result.方向 = (a.方向 + b.方向) div 2
  result.起笔 = a.起笔
  result.终笔 = b.终笔
  result.长度 = a.长度 + b.长度
  result.曲率 = (a.曲率 + b.曲率) / 2.0

# ============================================
# 偏旁范畴操作
# ============================================

proc 新建偏旁*(名称, 语义, 结构: string): 偏旁范畴 =
  result.名称 = 名称
  result.语义 = 语义
  result.结构 = 结构
  result.可组字 = @[]
  result.子范畴 = @[]

proc 添加子范畴*(父: var 偏旁范畴, 子: string) =
  父.子范畴.add(子)

proc 可组字*(偏旁: var 偏旁范畴, 字: string) =
  偏旁.可组字.add(字)

# ============================================
# 造字 = 范畴串联
# ============================================

proc 造字*(左, 右: 偏旁范畴, 结果字: string): 造字规则 =
  result.左范畴 = 左.名称
  result.右范畴 = 右.名称
  result.结果字 = 结果字
  result.语义合并 = 左.语义 & "+" & 右.语义

proc 验证造字*(规则: 造字规则, 字库: seq[汉字]): bool =
  for 字 in 字库:
    if 字.字形 == 规则.结果字:
      return true
  return false

# ============================================
# 范畴网络
# ============================================

proc 新建网络*(): 范畴网络 =
  result.节点 = @[]
  result.边 = @[]

proc 添加节点*(网: var 范畴网络, 节点: 偏旁范畴) =
  网.节点.add(节点)

proc 添加边*(网: var 范畴网络, a, b, 关系: string) =
  网.边.add((a, b, 关系))

