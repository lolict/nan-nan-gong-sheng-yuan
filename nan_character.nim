const 声母表*: array[23, string] = [
  "b", "p", "m", "f", "d", "t", "n", "l",
  "g", "k", "h", "j", "q", "x",
  "zh", "ch", "sh", "r", "z", "c", "s",
  "y", "w",
]

const 韵母表*: array[39, string] = [
  "a", "o", "e", "i", "u", "ü",
  "ai", "ei", "ui", "ao", "ou", "iu", "ie", "üe", "er",
  "an", "en", "in", "un", "ün",
  "ang", "eng", "ing", "ong",
  "ia", "iao", "ian", "iang", "iong",
  "ua", "uo", "uai", "uan", "uang",
  "üan", "üeng",
  # 注音用
  "zhi", "chi", "shi",
]

proc 拼音分解*(拼音: string): (string, string, uint8) =
  # 分解 "xiū" → ("x", "iu", 1)
  var 声母 = ""
  var 韵母 = ""
  var 声调: uint8 = 0

  # 提取声调标记
  var 纯拼音 = 拼音
  for c in 纯拼音:
    case c
    of 'ā', 'ē', 'ī', 'ō', 'ū', 'ǖ': 声调 = 1
    of 'á', 'é', 'í', 'ó', 'ú', 'ǘ': 声调 = 2
    of 'ǎ', 'ě', 'ǐ', 'ǒ', 'ǔ', 'ǚ': 声调 = 3
    of 'à', 'è', 'ì', 'ò', 'ù', 'ǜ': 声调 = 4
    else: discard

  # 去声调符号
  var 去声调 = ""
  for c in 纯拼音:
    case c
    of 'ā', 'á', 'ǎ', 'à': 去声调.add('a')
    of 'ē', 'é', 'ě', 'è': 去声调.add('e')
    of 'ī', 'í', 'ǐ', 'ì': 去声调.add('i')
    of 'ō', 'ó', 'ǒ', 'ò': 去声调.add('o')
    of 'ū', 'ú', 'ǔ', 'ù': 去声调.add('u')
    of 'ǖ', 'ǘ', 'ǚ', 'ǜ': 去声调.add('ü')
    else: 去声调.add(c)

  # 匹配声母
  for s in 声母表:
    if 去声调.startsWith(s):
      声母 = s
      韵母 = 去声调[s.len..^1]
      break
  if 声母.len == 0:
    韵母 = 去声调

  return (声母, 韵母, 声调)

