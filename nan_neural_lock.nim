proc 注入负样本*(神经: var 全局神经系统) =
  # 主人告诉AI的历史撞墙记录
  let 历史撞墙 = @[
    新建负样本(
      "韵母容器只有7个符号",
      "韵母实际有37个，不是7个",
      "nan_dimension.nim",
      "韵母集必须包含全部37个韵母",
      "符号体系混乱"
    ),
