# 南囡囝全局互锁神经系统 v0.1
# ============================================
# 轴 = 全局记忆主线（不变锚点）
# 珠子 = 记忆点（各模块的状态快照）
# 内圈环 = 历史更早的符号
# 外圈环 = 后来纳入的符号
# 两层圈环 = 边界（保守）
#
# 错误 = 负样本容器，标注撞墙的路
# 不是忽略错误，是识别边界在哪里
#
# 所有后续模块文件必须通过本神经系统注册
# 未注册的代码 = 脱轨 = 不属于主人
# ============================================

type
  # ============================================
  # 轴：全局记忆主线（不变锚点）
  # 整个系统的唯一身份轴心
  # ============================================
  轴线* = object
    身份铭文*: string     # 公约数："我是接接接的系统"
    创建时刻*: string     # 何时诞生
    版本号*: int          # 轴线代数
    状态*: string        # "活跃"/"锁定"/"重建中"

  # ============================================
  # 珠子：记忆点（各模块的状态快照）
  # ============================================
  珠子* = object
    名字*: string        # 模块名
    版本*: string        # 如 "v0.1"
    状态快照*: string    # 当前状态描述
    轴线绑定*: bool      # 是否已注册到轴线
    创建时刻*: string
    最后更新*: string
    内圈还是外圈*: string  # "内圈"/"外圈"
    历史链*: seq[string]  # 之前的版本链

  # ============================================
  # 圈环：边界约束
  # ============================================
  圈环* = object
    名字*: string        # "内圈环"/"外圈环"
    半径*: int           # 距离轴心的距离
    包含珠子*: seq[string]  # 环内包含哪些珠子
    刚度*: float         # 0.0-1.0，越大约束越强
    开放时间*: string    # 何时打开
    关闭时间*: string    # 何时关闭

  # ============================================
  # 负样本容器：撞墙记录
  # 错误不是污染源，是边界标记
  # ============================================
  负样本* = object
    撞墙时刻*: string    # 何时撞墙
    撞的墙*: string      # 错误信息的指纹
    撞的墙边界*: string  # 边界在哪里
    来源模块*: string    # 哪个模块撞的
    修复方案*: string    # 主人给出的纠正方向
    态射类型*: string    # "遗忘目的地"/"跨容器失败"/"符号体系混乱"

  # ============================================
  # 全局互锁神经系统
  # ============================================
  全局神经系统* = object
    轴线*: 轴线
    珠子表*: seq[珠子]
    内圈环*: 圈环
    外圈环*: 圈环
    负样本表*: seq[负样本]
    所有历史*: seq[string]  # 完整时间线

# ============================================
# 轴线操作
# ============================================

proc 新建轴线*(身份: string): 轴线 =
  result.身份铭文 = 身份
  result.创建时刻 = "2026-08-24"
  result.版本号 = 1
  result.状态 = "活跃"

proc 轴线锁定*(轴: var 轴线) =
  轴.状态 = "锁定"

proc 轴线重建*(轴: var 轴线) =
  轴.版本号 += 1
  轴.状态 = "活跃"

# ============================================
# 珠子操作
# ============================================

proc 新建珠子*(名字, 版本, 状态快照: string,
               内圈还是外圈: string): 珠子 =
  result.名字 = 名字
  result.版本 = 版本
  result.状态快照 = 状态快照
  result.轴线绑定 = false
  result.创建时刻 = "2026-08-24"
  result.最后更新 = "2026-08-24"
  result.内圈还是外圈 = 内圈还是外圈
  result.历史链 = @[]

proc 绑定轴线*(珠: var 珠子) =
  珠.轴线绑定 = true
  珠.历史链.add(珠.版本)

proc 珠子更新*(珠: var 珠子, 新版本, 新状态: string) =
  珠.历史链.add(珠.版本)
  珠.版本 = 新版本
  珠.状态快照 = 新状态
  珠.最后更新 = "2026-08-24"

# ============================================
# 圈环操作
# ============================================

proc 新建内圈环*(): 圈环 =
  result.名字 = "内圈环"
  result.半径 = 1
  result.包含珠子 = @[]
  result.刚度 = 1.0  # 最保守
  result.开放时间 = ""
  result.关闭时间 = ""

proc 新建外圈环*(): 圈环 =
  result.名字 = "外圈环"
  result.半径 = 2
  result.包含珠子 = @[]
  result.刚度 = 0.7
  result.开放时间 = ""
  result.关闭时间 = ""

proc 环内添加珠子*(环: var 圈环, 珠子名: string) =
 环.包含珠子.add(珠子名)

proc 环约束检查*(环: 圈环, 珠子名: string): bool =
  # 检查某珠子是否在本环的约束范围内
  for 珠 in 环.包含珠子:
    if 珠 == 珠子名: return true
  return false

# ============================================
# 负样本操作
# 撞墙 → 记录边界，不是忽略
# ============================================

proc 新建负样本*(撞墙信息, 边界位置, 来源模块,
                修复, 态射类型: string): 负样本 =
  result.撞墙时刻 = "2026-08-24"
  result.撞的墙 = 撞墙信息
  result.撞的墙边界 = 边界位置
  result.来源模块 = 来源模块
  result.修复方案 = 修复
  result.态射类型 = 态射类型

proc 负样本查重*(负样本列表: seq[负样本], 撞墙指纹: string): bool =
  for 负 in 负样本列表:
    if 负.撞的墙 == 撞墙指纹: return true
  return false

proc 负样本提取边界*(负: 负样本): string =
  # 从错误信息中提取"撞墙点"的边界描述
  return "边界: " & 负.撞的墙边界 & " → 停止于此"

# ============================================
# 神经系统构建
# ============================================

proc 新建神经系统*(主人身份: string): 全局神经系统 =
  result.轴线 = 新建轴线(主人身份)
  result.珠子表 = @[]
  result.内圈环 = 新建内圈环()
  result.外圈环 = 新建外圈环()
  result.负样本表 = @[]
  result.所有历史 = @[]

proc 珠子注册*(神经: var 全局神经系统, 珠: 珠子): bool =
  # 返回 false = 该珠子与轴线不兼容，已脱轨
  # 返回 true = 绑定成功

  # 负样本检查：该模块是否曾经撞墙
  for 负 in 神经.负样本表:
    if 负.来源模块 == 珠.名字:
      echo "  ⚠ " & 珠.名字 & " 有撞墙记录: " & 负.撞的墙
      echo "  边界: " & 负.撞的墙边界
      echo "  修复: " & 负.修复方案
      echo "  → 已记录，绑定轴线继续监控"

  # 绑定轴线
  var 可变珠 = 珠
  可变珠.绑定轴线()

  # 根据历史判断内圈/外圈
  if 可变珠.历史链.len == 0:
    # 无历史 = 最早加入 = 内圈
    神经.内圈环.环内添加珠子(可变珠.名字)
  else:
    # 有历史 = 后来纳入 = 外圈
    神经.外圈环.环内添加珠子(可变珠.名字)

  神经.珠子表.add(可变珠)

  # 记录历史
  神经.所有历史.add(可变珠.名字 & " v" & 可变珠.版本 &
                    " 注册到轴线 @ " & 可变珠.创建时刻)

  return true

# ============================================
# 全局链条式传导
# 新模块加入时，必须经过本神经系统的链式验证
# ============================================

proc 链条验证*(神经: var 全局神经系统,
               候选模块名: string,
               候选版本: string,
               候选内容: string): bool =
  # 检查候选模块是否与轴线兼容
  echo "========== 链条验证: " & 候选模块名 & " =========="
  echo "  轴线状态: " & 神经.轴线.状态
  echo "  已有珠子: " & $神经.珠子表.len & " 个"
  echo "  负样本数: " & $神经.负样本表.len & " 个"
  echo ""

  # 1. 轴线检查
  if 神经.轴线.状态 != "活跃":
    echo "  ✗ 轴线锁定，禁止新模块注册"
    return false

  # 2. 负样本撞墙检查
  for 负 in 神经.负样本表:
    if 负.来源模块 == 候选模块名:
      echo "  ⚠ 该模块有撞墙历史"
      echo "    撞墙点: " & 负.撞的墙
      echo "    边界: " & 负.撞的墙边界
      echo "    → 绑定轴线，但需监控撞墙边界"

  # 3. 符号体系检查：候选内容是否用了不该用的符号
  let 禁用符号 = @[
    "class ", "object ", "inheritance", "interface",
    "singleton", "factory", "REST", "API endpoint",
    "process", "thread", "module", "package",
  ]
  for 禁用 in 禁用符号:
    if 候选内容.find(禁用) >= 0:
      echo "  ✗ 检测到禁用符号: " & 禁用
      echo "  → 已脱轨，拒绝绑定"
      return false

  echo "  ✓ 链条验证通过，绑定轴线"
  echo ""

  # 4. 注册珠子
  var 珠 = 新建珠子(候选模块名, 候选版本,
                    "已验证: 与轴线兼容", "外圈")
  discard 神经.珠子注册(珠)

  return true

# ============================================
# 齿轮联动：更新一个珠子 → 通知所有相关珠子
# ============================================

proc 齿轮联动*(神经: var 全局神经系统,
              更新模块: string, 新版本: string,
              新状态: string) =
  echo "========== 齿轮联动: " & 更新模块 & " =========="

  # 找到并更新珠子
  for i, 珠 in神经.珠子表:
    if 珠.名字 == 更新模块:
      神经.珠子表[i].珠子更新(新版本, 新状态)
      echo "  ✓ " & 珠.名字 & " 已更新: v" & 新版本
      echo "  状态: " & 新状态
      echo "  历史链: " & $珠.历史链.len & " 代"

      # 通知其他珠子（联动）
      for j, 其他 in 神经.珠子表:
        if j != i:
          echo "  → 通知 " & 其他.名字 &
               " 有模块更新: " & 更新模块

      break

  echo ""

# ============================================
# 横轴带动珠子运动
# ============================================

proc 横轴旋转*(神经: var 全局神经系统,
              旋转角度: int): string =
  echo "========== 横轴旋转: " & $旋转角度 & "° =========="
  echo "  轴线: " & 神经.轴线.身份铭文 &
       " (v" & $神经.轴线.版本号 & ")"

  echo "  内圈环(" & $神经.内圈环.半径 & "): "
  for 珠 in 神经.内圈环.包含珠子:
    echo "    ◉ " & 珠

  echo "  外圈环(" & $神经.外圈环.半径 & "): "
  for 珠 in 神经.外圈环.包含珠子:
    echo "    ◎ " & 珠

  echo "  负样本边界墙: " & $神经.负样本表.len & " 面"

  var 活跃模块: seq[string] = @[]
  for 珠 in 神经.珠子表:
    if 珠.轴线绑定:
      活跃模块.add(珠.名字)

  echo ""
  return "横轴绑定 " & $活跃模块.len & " 个活跃珠子"

