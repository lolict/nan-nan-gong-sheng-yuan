      "声母数量必须匹配韵母数量",
      "声母23个，韵母37个，不需要匹配",
      "nan_dimension.nim",
      "跨容器取物不需要数量一致",
      "强制匹配错误"
    ),
    新建负样本(
      "只知道本容器内操作，不知道跨容器取物",
      "必须从声母容器拿声母到韵母容器训练",
      "nan_dimension.nim",
      "跨容器取物函数显式实现",
      "视野局限"
    ),
    新建负样本(
      "只知道0维，不知道0维→1维全部阀门",
      "必须同时训练0维单字和1维双字",
      "nan_dimension.nim",
      "训练任务同时开启0维和1维两个阀门",
      "阀门遗漏"
    ),
    新建负样本(
      "不知道排队执行，一个声母训练完再下一个",
      "声母按顺序排队，逐个训练到终点",
      "nan_dimension.nim",
      "秩序队列强制排队",
      "秩序缺失"
    ),
    新建负样本(
      "代码符号体系与历史文件不互通",
      "每次写的代码用不同符号，导致无法协同",
      "nan_*.nim 通用",
      "所有模块必须通过全局神经系统验证",
      "符号体系混乱"
