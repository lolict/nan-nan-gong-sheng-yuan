# 5. 零维符号核心操作
# ============================================

proc 码位到拼音*(码位索引: uint8): string =
  if int(码位索引) < 64:
    result = 零维符号表[码位索引].拼音值

proc 拼音查码位*(拼音: string): int =
  for i in 0..<64:
    if 零维符号表[i].拼音值 == 拼音:
      return i
  return -1

proc 获取配对*(码位索引: uint8): uint8 =
  if int(码位索引) < 64:
    let 配对符 = 零维符号表[码位索引].配对
    for i in 0..<64:
      if 零维符号表[i].字符 == 配对符:
        return uint8(i)
  return 0

proc 容器跳转*(当前容器, 目标容器: uint8): bool =
  # 二元配对：同容器内跳
  # 三元镜像：跨容器跳（通过配对找中心）
  if 当前容器 == 目标容器:
    result = true  # 二元同容器
  else:
    result = false # 三元跨容器

# ============================================
# 6. 二元/三元配对（继承v0.3）
# ============================================
# 二元 = 近义词 = 公倍数 = 两端克隆（不在乎中心）
# 三元 = 反义词 = 公约数 = 中心裁判（先中心再分叉）

proc 二元克隆*(a, b: uint8): (uint8, uint8) =
  # 两端克隆：复制a到b的位置（或b到a）
  # 不管中间虚无是什么
  (a, b)

proc 三元对称*(a, center, b: uint8): (uint8, uint8, uint8) =
  # 中心对称：以center为锚点，a和b镜像对称
  # 先定中心，再向两端发散
  (a, center, b)

proc 二元近义判断*(a, b: uint8): bool =
  # 同容器 = 近义词（公倍数关系）
  if int(a) < 64 and int(b) < 64:
    result = 零维符号表[a].容器编号 == 零维符号表[b].容器编号

proc 三元反义判断*(a, b: uint8): bool =
  # 不同容器 + 有配对关系 = 反义词（公约数关系）
  if int(a) < 64 and int(b) < 64:
    let 配对A = 获取配对(a)
    let 配对B = 获取配对(b)
    result = (配对A == b) or (配对B == a)

# ============================================
# 7. 多维跳转（继承v0.2）
# ============================================

proc 零维跳转*(当前位置, 目标: int): bool =
  # 点到点跳转：最短距离 = 绝对值差
  let 距离 = abs(当前位置 - 目标)
  result = 距离 == 1  # 只跳相邻点

proc 一维跳转*(当前位置, 目标: int): int =
  # 线串联：顺跳或倒跳
  if 目标 > 当前位置:
    result = 1   # 向前
  elif 目标 < 当前位置:
    result = -1  # 向后
  else:
    result = 0   # 不动

proc 二维跳转*(当前位置, 目标: (int,int)): int =
  # 面并集：斜线进位（走对角线）
  let dx = abs(当前位置[0] - 目标[0])
  let dy = abs(当前位置[1] - 目标[1])
  result = max(dx, dy)  # 切比雪夫距离

proc 三维跳转*(当前位置, 目标: (int,int,int)): int =
  # 体容器：三维相位定位
  let dx = abs(当前位置[0] - 目标[0])
  let dy = abs(当前位置[1] - 目标[1])
  let dz = abs(当前位置[2] - 目标[2])
  result = dx + dy + dz

