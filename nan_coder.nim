# 南囡囝编码系统 v0.8
# 新增：微内核字节码虚拟机 + 零维拼音符号体系
# 目标：不依赖gcc/命令行/外部运行时，在沙箱内自举执行

# ============================================
# 1. 核心类型（继承v0.7）
# ============================================

type
  # 零维起点 = 公约数 = 时间点
  零维* = object
    名称*: string
    坐标*: (int, int, int)
    状态*: string

  # 一维时间 = 串联线
  一维时间* = object
    起点*: 零维
    终点*: 零维
    节点数*: int
    长度*: float

  # 公倍数 = 高维并集节点
  公倍数* = object
    名称*: string
    维度*: int
    父节点*: int
    子节点*: seq[int]

  # 空集容器
  空集容器* = object
    码位*: (int, int, int)
    所有者*: uint8
    内容*: seq[公倍数]
    时间线*: 一维时间
    状态*: string

  # 归属权
  归属权* = object
    名称*: string
    正面*: bool
    可控方*: string
    价值*: float

  # ========== v0.8 新增 ==========

  # 零维符号 = 拼音韵母码位
  # 一次性机会进制：一个人就是一个人，不把十个人当成一个人用
  # 零维符号 = 点，不增长一维线长度
  零维符号* = object
    字符*: string           # Unicode字符本身
    码位索引*: uint8        # 在码位表中的位置 0-63
    拼音值*: string         # 自定义拼音读音
    容器编号*: uint8        # 属于哪个容器
    韵母类型*: string       # "单韵母"/"复韵母"/"前鼻"/"后鼻"/"声母"/"特殊"
    大小写*: string         # "大写"/"小写"/"独立"  (独立=无大小写)
    配对*: string           # 配对的另一个符号

  # 码位容器 = 零维符号的集装箱
  # 64进制三维容器：64×64×64 = 262144 个码位
  码位容器* = object
    编号*: uint8           # 容器编号
    容量*: int             # 固定64
    符号表*: array[64, 零维符号]  # 64个零维符号
    相邻容器*: seq[uint8]   # 相邻容器编号

  # 微内核字节码指令
  # 不依赖任何外部指令集，自定义产权
  微指令* = enum
    NOP = 0          # 空操作
    LOAD = 1         # 加载常量
    STORE = 2        # 存储变量
    ADD = 3          # 加法
    SUB = 4          # 减法
    MUL = 5          # 乘法
    DIV = 6          # 除法（公约数）
    MOD = 7          # 取模（公倍数）
    CMP = 8          # 比较（归属权判断）
    JMP = 9          # 无条件跳转
    JZ = 10          # 零跳转（虚无判断）
    JNZ = 11         # 非零跳转（存在判断）
    CALL = 12        # 调用子程序
    RET = 13         # 返回
    PUSH = 14        # 压栈（一维时间聚焦）
    POP = 15         # 弹栈
    HALT = 16        # 停机
    SYSCALL = 17     # 系统调用
    COPY = 18        # 二元克隆（公倍数复制）
    MIRROR = 19      # 三元镜像（公约数对称）
    FILL = 20        # 填充空集容器
    EXTRACT = 21     # 截取节点
    PHASE = 22       # 相位容器定位
    DIM0 = 23       # 零维跳转（点定位）
    DIM1 = 24       # 一维跳转（线串联）
    DIM2 = 25       # 二维跳转（面并集）
    DIM3 = 26       # 三维跳转（体容器）
    OWNR = 27       # 归属权判断

  # 字节码函数
  字节码函数* = object
    名称*: string
    参数数量*: uint8
    局部变量数*: uint8
    指令序列*: seq[uint8]   # 字节码序列
    码位表*: seq[int]       # 指令对应的码位坐标

  # 字节码模块
  字节码模块* = object
    版本*: string
    函数表*: seq[字节码函数]
    常量池*: seq[string]
    入口函数*: int

  # 微内核虚拟机状态
  虚拟机状态* = object
    寄存器*: array[8, int64]    # 8个通用寄存器
    指令指针*: int              # 当前执行位置
    栈指针*: int               # 栈顶位置
    栈*: array[256, int64]     # 256层栈
    内存*: array[1024, uint8]   # 1KB数据内存
    运行*: bool                 # 是否在运行
    状态*: string              # "虚无"/"执行中"/"停机"

  # 码位进制（替代传统进制）
  # 传统进制：10个人当1个人用（N进制进位）
  # 码位进制：64个符号，1个符号就是1个码位
  码位进制* = object
    容器数*: uint8              # 容器数量
    每容器码数*: int            # 固定64
    容器*: array[64, 码位容器]  # 最多64个容器
    当前容器*: uint8            # 当前活跃容器
    当前索引*: uint8            # 当前容器内索引

