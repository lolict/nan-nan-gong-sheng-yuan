# ============================================
# 4. 微内核字节码虚拟机
# ============================================
# 不依赖gcc/命令行/外部生态
# 零外部依赖，自举执行

proc 创建虚拟机*(): 虚拟机状态 =
  result.寄存器 = [0'i64, 0, 0, 0, 0, 0, 0, 0]
  result.指令指针 = 0
  result.栈指针 = 0
  result.运行 = true
  result.状态 = "虚无"

proc 执行指令*(vm: var 虚拟机状态, 模块: 字节码模块): string =
  # 简化执行器：遍历字节码序列
  var ip = 0
  while ip < 模块.函数表[0].指令序列.len and vm.运行:
    let op = 模块.函数表[0].指令序列[ip]
    case op:
    of ord(NOP):
      discard
    of ord(ADD):
      if vm.栈指针 >= 2:
        let b = vm.栈[vm.栈指针]
        dec vm.栈指针
        vm.栈[vm.栈指针] = vm.栈[vm.栈指针] + b
    of ord(SUB):
      if vm.栈指针 >= 2:
        let b = vm.栈[vm.栈指针]
        dec vm.栈指针
        vm.栈[vm.栈指针] = vm.栈[vm.栈指针] - b
    of ord(PUSH):
      if vm.栈指针 < 255:
        vm.栈[vm.栈指针] = vm.寄存器[0]
        inc vm.栈指针
    of ord(POP):
      if vm.栈指针 > 0:
        dec vm.栈指针
        vm.寄存器[0] = vm.栈[vm.栈指针]
    of ord(HALT):
      vm.运行 = false
      vm.状态 = "停机"
    else:
      discard
    inc ip
  result = "执行完毕，停机"

