proc 截取节点*(源: string, 节点ID: int): 公倍数 =
  result = 公倍数(
    名称: 源 & "节点" & $节点ID,
    维度: 3,
    父节点: -1,
    子节点: @[]
  )

proc 填充空集*(容器: var 空集容器, 节点: 公倍数) =
  容器.内容.add(节点)
  容器.状态 = "填充中"

proc 聚焦处理*(容器: var 空集容器): string =
  容器.状态 = "存在"
  result = "已聚焦: " & $容器.内容.len & "个节点"

proc 归属权判断*(权: 归属权): string =
  if 权.正面:
    result = "[归属我们] " & 权.名称 & " = " & $权.价值
  else:
    result = "[归属他们] " & 权.名称 & " = " & $权.价值

