# 5. 容器进制索引（64×64×64）
# ============================================
# 三维码位：容器号×64² + 槽位号×64 + 索引
# O(1)查表：给定三维坐标，直接计算一维偏移

type
  三维码位* = object
    x*: uint8   # 容器号（0-63）
    y*: uint8   # 槽位号（0-63）
    z*: uint8   # 索引（0-63）
  
  码位坐标* = object
    容器*: uint8
    槽位*: uint8
    索引*: uint8

proc 码位编码*(c, s, i: uint8): uint32 =
  # 三维码位压缩成一维偏移
  # 容器×64×64 + 槽位×64 + 索引
  result = (uint32(c) * 64'u32 + uint32(s)) * 64'u32 + uint32(i)

proc 码位解码*(码: uint32): 三维码位 =
  # 一维偏移解码成三维码位
  let 总槽位 = 码 div 64'u32
  result.z = uint8(码 mod 64'u32)
  result.y = uint8(总槽位 mod 64'u32)
  result.x = uint8(总槽位 div 64'u32)

