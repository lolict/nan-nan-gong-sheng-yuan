# 6. 预加载符号索引表（O(1)查表）
# ============================================
# 预加载 = 启动时一次性构建索引表
# 运行时只查表不生成

type
  符号索引* = object
    声母*: array[23, uint8]    # 声母→码位
    韵母*: array[37, uint8]    # 韵母→码位
    偏旁*: array[20, uint8]    # 偏旁→码位
    器官*: array[9, string]    # 器官→语义
    容器数*: uint8             # 容器总数
    符号总数*: uint16          # 符号总数

var 全局索引*: 符号索引

proc 初始化索引*() =
  # 域加载器：启动时一次性构建索引表
  # 只构建一次，运行时直接查表
  
  全局索引.容器数 = 4  # 声母容器0 + 韵母容器1 + 偏旁容器2 + 器官容器3
  
  # 声母索引
  for i in 0..<23:
    全局索引.声母[i] = 声母索引[i]
  
  # 韵母索引
  for i in 0..<37:
    全局索引.韵母[i] = 韵母索引[i]
  
  # 偏旁索引
  for i in 0..<20:
    全局索引.偏旁[i] = uint8(i)
  
  # 器官索引
  for i in 0..<9:
    全局索引.器官[i] = 器官表[i].语义
  
  # 计算符号总数
  全局索引.符号总数 = 23'u16 + 37'u16 + 20'u16 + 9'u16

proc 查声母码位*(声母: string): int =
  # O(1)查表
  for i in 0..<23:
    if 声母表[i] == 声母:
      return int(全局索引.声母[i])
  return -1

proc 查韵母码位*(韵母: string): int =
  # O(1)查表
  for i in 0..<37:
    if 韵母表[i] == 韵母:
      return int(全局索引.韵母[i])
  return -1

proc 查器官语义*(器官: string): string =
  # O(1)查表
  for i in 0..<9:
    if 器官表[i].符号 == 器官:
      return 全局索引.器官[i]
  return ""

