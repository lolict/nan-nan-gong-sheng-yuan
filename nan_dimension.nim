# 南囡囝维度秩序引擎 v0.1
# ============================================
# 几何方法论：
# 0维 = 公约数（静态点，边界起点）
# 1维 = 公倍数（动态线，折叠终点）
# 从0维到1维 = 奔向终点的过程
# 边界长度 = 量化统计的尺寸
#
# 核心操作：
# 跨容器取物 = 关系
# 当前容器分类 = 任务
# 韵母容器 × 声母容器 = 产权混合
# ============================================

type
  # ============================================
  # 0维：静态点 = 公约数
  # 不可分，是边界起点
  # ============================================
  零维* = object
    身份*: string          # 公约数名称："我"
    码位*: uint8           # 0-63码位，零维符号表位置
    容器的边界*: int       # 本容器包含多少个符号 = 边界尺寸

  # ============================================
  # 1维：动态线 = 公倍数的折叠过程
  # 起点=0维，终点=折叠边界
  # ============================================
  一维* = object
    起点*: 零维             # 从哪个零维开始
    终点*: int              # 折叠到达的边界（符号总数）
    当前层*: int            # 当前在第几层折叠
    宽度*: int              # 字符宽度：1=单字，2=双字，...n=n字

  # ============================================
  # 容器 = 存在单位，有自己的编码系统
  # ============================================
  容器* = object
    名称*: string
    类型*: string           # "韵母"/"声母"/"偏旁"/"笔画"...
    零维*: 零维              # 容器的静态起点
    一维*: 一维              # 容器的动态终点
    符号表*: seq[string]    # 本容器包含的符号集合
    产权*: int              # 本容器的产权值（可参与混合）

  # ============================================
  # 跨容器关系 = 从容器A取物到容器B训练
  # ============================================
  跨容器操作* = object
    源容器*: string         # 从哪个容器取
    目标容器*: string       # 放到哪个容器训练
    提取物*: string         # 提取的符号（声母/韵母/...）
    当前索引*: int          # 当前遍历到第几个
    状态*: string           # "等待"/"训练中"/"完成"/"切换下一个"

  # ============================================
  # 训练任务 = 一个声母遍历所有韵母
  # ============================================
  训练任务* = object
    声母*: string           # 当前参与训练的声母
    韵母表*: seq[string]    # 被训练的韵母集合
    零维已完成*: int        # 0维单字训练到了哪个
    一维已完成*: int        # 1维双字训练到了哪个
    韵母宽度*: int          # 当前韵母宽度（1字/2字）

  # ============================================
  # 产权流 = 两个容器的产权混合
  # ============================================
  产权混合* = object
    容器A*: 容器
    容器B*: 容器
    产权值A*: int
    产权值B*: int
    核心产权*: int          # v_core = (vA + vB) / 2
    是否侵权*: bool         # vA + vB == 2 * v_core → 侵权

  # ============================================
  # 秩序队列 = 按优先级排队执行的任务
  # ============================================
  秩序队列* = object
    等待中*: seq[训练任务]  # 排队的任务
    执行中*: 训练任务       # 当前正在执行
    已完成*: seq[训练任务]  # 执行完的任务

# ============================================
# 构建韵母容器（容器1）
# ============================================

proc 新建韵母容器*(): 容器 =
  let 韵母集 = @["a", "o", "e", "i", "u", "v",
                 "ai", "ei", "ui", "ao", "ou", "iu", "ie", "ve", "er",
                 "an", "en", "in", "un", "vn",
                 "ang", "eng", "ing", "ong",
                 "ia", "iao", "ian", "iang", "iong",
                 "ua", "uo", "uai", "uan", "uang", "van"]

  result.名称 = "韵母容器"
  result.类型 = "韵母"
  result.符号表 = 韵母集
  result.产权 = 韵母集.len  # 韵母数量 = 产权值

  # 0维：静态起点 = 韵母集合的边界
  result.零维.身份 = "韵母公约数"
  result.零维.容器的边界 = 韵母集.len
  result.零维.码位 = 0

  # 1维：动态终点 = 遍历完所有韵母
  result.一维.起点 = result.零维
  result.一维.终点 = 韵母集.len
  result.一维.当前层 = 1
  result.一维.宽度 = 1  # 单字宽度开始

# ============================================
# 构建声母容器（容器2）
# ============================================

proc 新建声母容器*(): 容器 =
  let 声母集 = @["b", "p", "m", "f", "d", "t", "n", "l",
                 "g", "k", "h", "j", "q", "x",
                 "zh", "ch", "sh", "r", "z", "c", "s", "y", "w"]

  result.名称 = "声母容器"
  result.类型 = "声母"
  result.符号表 = 声母集
  result.产权 = 声母集.len

  result.零维.身份 = "声母公约数"
  result.零维.容器的边界 = 声母集.len
  result.零维.码位 = 0

  result.一维.起点 = result.零维
  result.一维.终点 = 声母集.len
  result.一维.当前层 = 1
  result.一维.宽度 = 1

# ============================================
# 跨容器取物（关键操作！）
# AI撞墙点：它不知道要从另一个容器取东西
# ============================================

proc 跨容器取物*(源: 容器, 目标: var 容器, 提取索引: int): string =
  # 从源容器提取第n个符号，放到目标容器训练
  if 提取索引 >= 0 and 提取索引 < 源.符号表.len:
    return 源.符号表[提取索引]
  return ""

# ============================================
# 训练一个声母，遍历所有韵母（0维→1维全部阀门）
# ============================================

proc 新建训练任务*(声母: string, 韵母表: seq[string]): 训练任务 =
  result.声母 = 声母
  result.韵母表 = 韵母表
  result.零维已完成 = 0
  result.一维已完成 = 0
  result.韵母宽度 = 1  # 从单字开始

proc 训练一步*(任务: var 训练任务): (string, bool) =
  # 返回 (当前组合, 是否完成)
  if 任务.韵母宽度 == 1:
    # 0维：单字韵母训练
    if 任务.零维已完成 < 任务.韵母表.len:
      let 组合 = 任务.声母 & 任务.韵母表[任务.零维已完成]
      task.零维已完成 += 1
      return (组合, false)
    else:
      # 0维完成，切换到1维（双字）
      task.韵母宽度 = 2
      task.零维已完成 = 0

  if 任务.韵母宽度 == 2:
    # 1维：双字韵母训练
    if 任务.一维已完成 < 任务.韵母表.len:
      let 韵母2 = 任务.韵母表[任务.一维已完成]
      # 双字韵母：取两个韵母组合
      let idx2 = (任务.一维已完成 + 1) mod 任务.韵母表.len
      let 韵母组合 = 韵母2 & 任务.韵母表[idx2]
      let 组合 = 任务.声母 & 韵母组合
      task.一维已完成 += 1
      return (组合, false)
    else:
      # 1维完成，任务结束
      return ("", true)  # 空=完成

  return ("", true)

# ============================================
# 秩序队列：按优先级排队执行
# AI撞墙点：它不知道要排队，不知道先后秩序
# ============================================

proc 新建秩序队列*(): 秩序队列 =
  result.等待中 = @[]
  result.执行中.声母 = ""
  result.已完成 = @[]

proc 入队*(队列: var 秩序队列, 任务: 训练任务) =
  队列.等待中.add(任务)

proc 执行下一个*(队列: var 秩序队列, 韵母表: seq[string]): bool =
  # 执行队列中的下一个任务
  # 返回 true=还有任务，false=队列空
  if 队列.等待中.len == 0:
    return false

  # 取出队首
  var 当前任务 = 队列.等待中[0]
  队列.等待中.delete(0)

  # 训练直到完成
  var 完成 = false
  while not 完成:
    let (组合, 是否完成) = 当前任务.训练一步()
    if 组合 != "":
      echo "  训练: " & 组合
    完成 = 是否完成

  # 标记完成，入已完成列表
  队列.已完成.add(当前任务)
  echo "  ✓ 声母[" & 当前任务.声母 & "]训练完成"
  echo ""

  return 队列.等待中.len > 0

# ============================================
# 产权混合判定
# vA + vB == 2 * v_core → 侵权
# ============================================

proc 新建产权混合*(容器A, 容器B: 容器): 产权混合 =
  result.容器A = 容器A
  result.容器B = 容器B
  result.产权值A = 容器A.产权
  result.产权值B = 容器B.产权
  result.核心产权 = (result.产权值A + result.产权值B) div 2
  result.是否侵权 = (result.产权值A + result.产权值B) == 2 * result.核心产权

# ============================================
# 维度遍历：0维→1维的完整路径
# ============================================

proc 维度遍历*(容器A, 容器B: 容器): string =
  echo "========== 维度秩序引擎 v0.1 =========="
  echo "韵母容器 × 声母容器 = 产权混合训练"
  echo ""

  # 1. 先统计两个容器的边界
  echo "--- 边界统计 ---"
  echo "韵母容器边界(0维): " & $容器A.零维.容器的边界 & "个符号"
  echo "声母容器边界(0维): " & $容器B.零维.容器的边界 & "个符号"
  echo "韵母容器1维终点: " & $容器A.一维.终点 & "（遍历完所有韵母）"
  echo ""

  # 2. 产权混合
  var 混合 = 新建产权混合(容器A, 容器B)
  echo "--- 产权混合 ---"
  echo "韵母产权: " & $混合.产权值A
  echo "声母产权: " & $混合.产权值B
  echo "核心产权: " & $混合.核心产权
  echo "是否侵权: " & (if 混合.是否侵权: "是" else: "否")
  echo ""

  # 3. 核心训练：声母遍历韵母
  # AI撞墙点：它不知道要跨容器取声母来训练韵母
  echo "--- 跨容器训练（声母→韵母） ---"
  echo "从声母容器取物，放到韵母容器训练"
  echo "遍历: 0维(单字)→1维(双字) 全部阀门"
  echo ""

  var 队列 = 新建秩序队列()

  # 按顺序把所有声母入队
  for 声母 in 容器B.符号表:
    let 任务 = 新建训练任务(声母, 容器A.符号表)
    队列.入队(任务)

  # 按秩序队列执行
  echo "--- 秩序队列执行 ---"
  while 队列.执行下一个(容器A.符号表):
    discard

  echo ""
  echo "--- 统计 ---"
  echo "总声母: " & $容器B.符号表.len
  echo "总韵母: " & $容器A.符号表.len
  echo "单字组合(0维): " & $容器B.符号表.len & " × " & $容器A.符号表.len & " = " &
       $(容器B.符号表.len * 容器A.符号表.len)
  echo "双字组合(1维): 同上（韵母扩展为双字）"
  echo ""

  return "维度遍历完成: 0维→1维 全部阀门已激活"

# ============================================
# 演示入口
# ============================================

when isMainModule:
  # 创建两个容器
  var 韵母容器 = 新建韵母容器()
  var 声母容器 = 新建声母容器()

  # 执行维度遍历
  discard 维度遍历(韵母容器, 声母容器)

  echo "========== 维度秩序引擎 v0.1 完毕 =========="
  echo "秩序: 跨容器取物 → 排队训练 → 遍历0维→1维全部阀门"
