# nan_perceive.nim v0.1
# 南囡囝感知层引擎 — 输入层(五官) → 评价层(心/脑) → 输出层(情绪/行为)
#
# 原理来自 DeepSeek 导航书 1.2：
#   外感(眼耳口鼻皮肤) + 内感(五脏六腑) + 情绪(心脑) + 认知(脑髓) + 生理(六腑经络)
#   每一次感知 = 一个编码 = 一个状态 = 一个事件
#
# 零维符号原则：
#   预加载器官索引表，运行时只查表 O(1)，不搜索
#   器官本身不增长线长度，感知结果装进容器
#
# 禁止：类/对象/继承/多态/文件/目录/API/REST

import std/[strutils, tables]

# ==================== 器官索引表（预加载） ====================

# 器官管辖五大类，每类用独立进制容器
type
  器官类 = enum
    外感 = 0    # 眼耳口鼻皮肤 — 接收外部信号
    内感 = 1    # 五脏六腑 — 接收内部信号
    情绪 = 2    # 心脑 — 评价输出
    认知 = 3    # 脑髓 — 认知处理
    生理 = 4    # 六腑经络 — 生理响应

# 器官名称按类预加载，每类独立容器
# 外感15个：眼耳口鼻皮肤的细分
const 外感器官: array[15, string] = [
  "眼", "耳", "口", "鼻", "皮肤",
  "瞳孔", "耳膜", "舌", "喉", "指尖",
  "眼睑", "耳道", "唇", "鼻翼", "毛孔"
]

# 内感11个：五脏+六腑核心
const 内感器官: array[11, string] = [
  "心", "肝", "脾", "肺", "肾",
  "胃", "胆", "大肠", "小肠", "膀胱", "三焦"
]

# 情绪20个
const 情绪器官: array[20, string] = [
  "喜", "怒", "哀", "惧", "爱",
  "恶", "欲", "忧", "思", "悲",
  "恐", "惊", "嗔", "痴", "贪",
  "瞋", "慢", "疑", "妒", "惭"
]

# 认知10个
const 认知器官: array[10, string] = [
  "脑", "髓", "识", "神", "意",
  "志", "思", "虑", "智", "觉"
]

# 生理10个
const 生理器官: array[10, string] = [
  "经", "络", "脉", "穴", "气",
  "血", "津", "液", "精", "营"
]

# 器官总数 = 15+11+20+10+10 = 66
const 器官总数 = 66

# ==================== 感知编码 ====================
#
# 编码公式（导航书 1.1 变体）：
#   感知码 = 器官类 × 100 + 器官索引
#
# 器官类是高维（5进制），器官索引是低维（类内独立进制）
# 这样不同类的器官即使索引相同也不会冲突

proc 感知编码(类: 器官类; 索引: int): int =
  ## 把器官类和类内索引编码成一个感知码
  ## O(1) 直接计算，不查表
  result = ord(类) * 100 + 索引

proc 解码器官(码: int): tuple[类: 器官类; 索引: int] =
  ## 从感知码还原器官类和索引
  result = (器官类(码 div 100),码 mod 100)

proc 器官名(类: 器官类; 索引: int): string =
  ## O(1) 查器官名
  case 类
  of 外感:
    if 索引 in 0 ..< 外感器官.len: return 外感器官[索引]
  of 内感:
    if 索引 in 0 ..< 内感器官.len: return 内感器官[索引]
  of 情绪:
    if 索引 in 0 ..< 情绪器官.len: return 情绪器官[索引]
  of 认知:
    if 索引 in 0 ..< 认知器官.len: return 认知器官[索引]
  of 生理:
    if 索引 in 0 ..< 生理器官.len: return 生理器官[索引]
  return "未知"

# ==================== 感知事件 ====================
#
# 一次感知 = 一个编码 + 一个信号值 + 一个时间戳
# 装进容器（感知事件序列），不增长线长度

type
  感知事件 = object
    器官码: int       # 哪个器官感知的
    信号值: int       # 感知强度 0-100
    时间戳: int       # 感知时刻（逻辑时钟）
    源编码: int       # 信号来源编码（可关联外部符号）

# 感知事件容器（顺序队列）
var 感知流: seq[感知事件] = @[]
var 逻辑时钟: int = 0

proc 感知*(类: 器官类; 索引: int; 强度: int; 源: int = 0): int =
  ## 注册一次感知事件，返回事件在流中的位置
  ## 输入层入口：五官/内感信号从这里进入
  let 码 = 感知编码(类, 索引)
  逻辑时钟.inc
  感知流.add(感知事件(
    器官码: 码,
    信号值: clamp(强度, 0, 100),
    时间戳: 逻辑时钟,
    源编码: 源
  ))
  result = 感知流.high

# ==================== 评价层（心/脑） ====================
#
# 评价层对感知事件做判断：
#   高分 → 匹配资格，入选注意力
#   低分 → 排除，不分配时间空间
# 评价标准 = 信号强度阈值 + 器官权重

# 器官权重表（预加载）：不同器官的信号权重不同
const 外感权重 = 1.0
const 内感权重 = 1.2
const 情绪权重 = 1.5
const 认知权重 = 1.3
const 生理权重 = 0.8

proc 器官权重(类: 器官类): float =
  case 类
  of 外感: result = 外感权重
  of 内感: result = 内感权重
  of 情绪: result = 情绪权重
  of 认知: result = 认知权重
  of 生理: result = 生理权重

type
  评价结果 = object
    事件位置: int
    总分: float       # 信号强度 × 器官权重
    入选注意力: bool   # 总分 >= 阈值
    评价时刻: int

var 评价流: seq[评价结果] = @[]
const 注意力阈值 = 50.0

proc 评价*(事件位置: int): 评价结果 =
  ## 评价层处理：对一个感知事件打分
  ## 心/脑在这里做判断
  if 事件位置 < 0 or 事件位置 > 感知流.high:
    return 评价结果(事件位置: -1, 总分: 0, 入选注意力: false, 评价时刻: 逻辑时钟)

  let 事件 = 感知流[事件位置]
  let (类, _) = 解码器官(事件.器官码)
  let 分 = float(事件.信号值) * 器官权重(类)

  逻辑时钟.inc
  result = 评价结果(
    事件位置: 事件位置,
    总分: 分,
    入选注意力: 分 >= 注意力阈值,
    评价时刻: 逻辑时钟
  )
  评价流.add(result)

# ==================== 输出层（情绪/行为） ====================
#
# 输出层根据评价结果产生响应：
#   入选注意力 → 产生情绪/行为编码
#   未入选 → 静默（不分配时空）
#
# 输出映射表（预加载）：
#   器官类 → 对应输出类型

type
  输出类型 = enum
    静默输出 = 0
    情绪响应 = 1
    行为响应 = 2
    认知响应 = 3
    生理响应 = 4

  输出事件 = object
    源事件位置: int
    输出种类: 输出类型
    输出编码: int      # 输出符号编码
    输出强度: float
    输出时刻: int

var 输出流: seq[输出事件] = @[]

proc 器官类到输出(类: 器官类): 输出类型 =
  ## 输入器官类 → 输出类型的预加载映射
  case 类
  of 外感: result = 行为响应
  of 内感: result = 生理响应
  of 情绪: result = 情绪响应
  of 认知: result = 认知响应
  of 生理: result = 生理响应

proc 输出*(评价位置: int): int =
  ## 输出层处理：根据评价结果产生响应
  ## 返回输出事件在输出流中的位置
  if 评价位置 < 0 or 评价位置 > 评价流.high:
    return -1

  let 评 = 评价流[评价位置]
  if not 评.入选注意力:
    # 低分 → 静默，不分配时空
    逻辑时钟.inc
    输出流.add(输出事件(
      源事件位置: 评.事件位置,
      输出种类: 静默输出,
      输出编码: 0,
      输出强度: 0,
      输出时刻: 逻辑时钟
    ))
    return 输出流.high

  let 事件 = 感知流[评.事件位置]
  let (类, 索引) = 解码器官(事件.器官码)
  let 出 = 器官类到输出(类)

  # 输出编码 = 输出类型 × 100 + 器官索引
  let 出码 = ord(出) * 100 + 索引

  逻辑时钟.inc
  输出流.add(输出事件(
    源事件位置: 评.事件位置,
    输出种类: 出,
    输出编码: 出码,
    输出强度: 评.总分,
    输出时刻: 逻辑时钟
  ))
  result = 输出流.high

# ==================== 完整感知链路 ====================

proc 感知链路*(类: 器官类; 索引: int; 强度: int; 源: int = 0): int =
  ## 一键走完 输入→评价→输出 三层
  ## 返回输出事件位置
  let 入 = 感知(类, 索引, 强度, 源)
  let 评 = 评价(入)
  result = 输出(评价流.high)

# ==================== 间歇式迭代（导航书 1.3） ====================
#
# 人走路模式：不是每一步都校正，而是残差累加，超阈值才触发
#   触发 = 校正 if ||r|| > ε
#   纯动态累加 otherwise

const 残差阈值ε = 30.0   # 残差超过此值才触发校正
var 残差累加: float = 0
var 迭代计数: int = 0

proc 间歇迭代*(新感知强度: float): float =
  ## 间歇式迭代：残差累加到阈值才校正
  ## 返回当前最优估计值
  迭代计数.inc
  残差累加 += abs(新感知强度 - 50.0)  # 以50为基准计算残差

  if 残差累加 > 残差阈值ε:
    # 触发校正：卡尔曼增益式融合
    let 增益 = 残差累加 / (残差累加 + 10.0)
    result = 50.0 + 增益 * (新感知强度 - 50.0)
    残差累加 = 0  # 校正后重置
  else:
    # 纯动态累加，不校正
    result = 50.0

# ==================== 查询接口 ====================

proc 感知总数*: int = 感知流.len
proc 评价总数*: int = 评价流.len
proc 输出总数*: int = 输出流.len

proc 查感知*(位置: int): string =
  ## 可读的感知事件描述
  if 位置 < 0 or 位置 > 感知流.high: return "无效位置"
  let e = 感知流[位置]
  let (类, 索引) = 解码器官(e.器官码)
  result = $类 & "(" & 器官名(类, 索引) & ") 强度=" & $e.信号值 &
           " t=" & $e.时间戳

proc 查输出*(位置: int): string =
  ## 可读的输出事件描述
  if 位置 < 0 or 位置 > 输出流.high: return "无效位置"
  let e = 输出流[位置]
  result = $e.输出种类 & " 编码=" & $e.输出编码 &
           " 强度=" & $e.输出强度 & " t=" & $e.输出时刻

