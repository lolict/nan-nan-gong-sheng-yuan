#   存储即生成，生成即输出，输出即存储
#   存储即记忆，记忆即心算
#   输入法与思维一体化
#   存算一体化
#
# 不用任何外部符号
#   所有符号 = 声母+韵母+笔画+偏旁
#   输入法自带进制索引
