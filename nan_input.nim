#   编译器 = 激活钥匙
#   激活后：任意数字活动
#   不固定时：活动状态
#   固定时：按排列顺序定位权限和数值
#   位置决定大小 = 加法统计法的位置
#   临时上任的官员 = 动态赋权
# ============================================

