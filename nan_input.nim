# ============================================
# 符号构造（只用声母韵母，不借外部编码）
# ============================================

proc 新建符号*(字形: string, 声母: string, 韵母: string, 声调: uint8,
               笔画数: uint8, 偏旁: string): 符号 =
  result.字形 = 字形
  result.声母 = 声母
  result.韵母 = 韵母
  result.声调 = 声调
  result.笔画数 = 笔画数
  result.偏旁 = 偏旁
  result.活态 = true
  result.层级 = 0
  # 计算拼音
  result.拼音 = 声母 & 韵母
  if 声调 > 0:
    result.拼音 &= $声调

# ============================================
# 码位计算（进制索引）
# ============================================

proc 计算码位*(声母: string, 韵母: string, 声调: uint8): uint16 =
  ## 用声母韵母声调计算码位
  ## 这就是输入法自己的索引进制
  var 声母位置: uint16 = 0
  var 韵母位置: uint16 = 0

  for i, s in 声母表:
    if s == 声母:
      声母位置 = uint16(i)
      break

  for i, y in 韵母表:
    if y == 韵母:
      韵母位置 = uint16(i)
      break

  # 码位 = 声母位置 * 韵母数量 + 韵母位置 + 声调偏移
  result = 声母位置 * uint16(韵母表.len) + 韵母位置
  if 声调 > 0:
    result = result * 5 +声调  # 声调作为额外权重

# ============================================
# 存储即生成（存入时就是生成时）
# ============================================

proc 存入符号*(容器: var 三维数据容器, 符号: 符号): bool =
  ## 存入符号 = 生成符号 = 同时完成
  ## 存入时就算好码位、活态、层级
  if 容器.当前已用 >= 容器.容量:
    return false  # 满了，存不进去

  # 计算码位
  var 码 = 计算码位(符号.声母, 符号.韵母, 符号.声调)
  符号.码位 = 码

  # 存入符号表
  容器.符号表.add(符号)
  容器.当前已用 += 1

  # 更新索引表（按码位排序）
  容器.索引表.add(码)
  容器.索引表.sort(system.cmp[uint16])

  # 如果是活态，加入活码表
  if 符号.活态:
    容器.活码表.add(码)
  else:
    容器.固定码表.add(码)

  return true

proc 取出符号*(容器: 三维数据容器, 码位: uint16): 符号 =
  ## 取出符号 = 输出符号
  for s in 容器.符号表:
    if s.码位 == 码位:
      return s
  # 没找到，返回空符号
  result.字形 = ""
  result.码位 = 0

# ============================================
# 活码激活（编译器钥匙机制）
# ============================================

proc 创建活码*(钥匙码位: uint16, 目标起始: uint16, 目标终止: uint16): 活码 =
  result.钥匙码位 = 钥匙码位
  result.目标起始 = 目标起始
  result.目标终止 = 目标终止
  result.状态 = "活动"
  result.当前位置 = 目标起始

proc 激活活码*(活码: var 活码): bool =
  ## 用编译器钥匙激活活码
  ## 激活后：任意数字活动
  if 活码.状态 != "活动":
    return false
  活码.状态 = "激活"
  活码.当前位置 = 活码.目标起始
  return true

proc 活码走一步*(活码: var 活码): bool =
  ## 活码活动一步
  ## 位置决定大小 = 加法统计法的位置
  if 活码.状态 != "激活":
    return false
  活码.当前位置 += 1
  if 活码.当前位置 > 活码.目标终止:
    活码.状态 = "固定"
    return false  # 到头了
  return true

proc 固定活码*(活码: var 活码, 容器: var 三维数据容器) =
  ## 固定活码：按当前排列顺序定位权限和数值
  活码.状态 = "固定"
  # 把这个范围内的码位从活码表移到固定码表
  for i in 活码.目标起始 .. 活码.目标终止:
    for idx, 码 in 容器.活码表:
      if 码 == i:
        容器.活码表.delete(idx)
        if i notin 容器.固定码表:
          容器.固定码表.add(i)
        break

# ============================================
# 区块链传导（层级关系追踪记忆锚点）
# ============================================

proc 创建区块链传导*(层号: uint8, 记忆锚点: uint16): 区块链传导 =
  result.层号 = 层号
  result.父链 = 0
  result.子链表 = @[]
  result.状态 = "活跃"
  result.记忆锚点 = 记忆锚点

proc 添加子链*(父链: var 区块链传导, 子链位置: uint16) =
  父链.子链表.add(子链位置)

proc 传导至子链*(父链: 区块链传导, 记忆数据: uint16): bool =
  ## 区块链式传导：父链传导到子链
  if 父链.状态 != "活跃":
    return false
  # 记忆锚点传递到所有子链
  for 子 in 父链.子链表:
    # 子链接收记忆锚点
    discard
  return true

# ============================================
# 心算（存入时就算好，不需要运行时再算）
# ============================================

proc 心算加法*(左: uint16, 右: uint16): 心算单元 =
  result.运算类型 = "加"
  result.左操作数 = 左
  result.右操作数 = 右
  result.结果 = 左 + 右
  result.触发条件 = "心算时"

proc 心算比较*(左: uint16, 右: uint16): 心算单元 =
  result.运算类型 = "比"
  result.左操作数 = 左
  result.右操作数 = 右
  if 左 > 右:
    result.结果 = 1  # 左大于右
  elif 左 < 右:
    result.结果 = 2  # 右大于左
  else:
    result.结果 = 0  # 相等

proc 心算匹配*(目标: uint16, 参照表: seq[uint16]): (bool, uint16) =
  ## 在参照表中找匹配的符号
  for i, 码 in 参照表:
    if 码 == 目标:
      return (true, uint16(i))
  return (false, 0)

# ============================================
# 进制层（进制的层级关系）
# ============================================

proc 新建进制层*(层号: uint8, 基数: uint16): 进制层 =
  result.层号 = 层号
  result.基数 = 基数
  result.当前值 = 0
  result.上限 = 基数 - 1
  result.下一层触发 = false

proc 进制走一步*(层: var 进制层): bool =
  ## 进制走一步，触发加法统计法
  层.当前值 += 1
  if 层.当前值 > 层.上限:
    层.当前值 = 0
    层.下一层触发 = true
    return false  # 触发了进位
  return true

proc 获取进制位置*(层: 进制层): uint16 =
  ## 获取当前进制位置
  ## 位置决定大小
  return 层.当前值

