# 南囡囝范畴论编码系统 v0.1
# ============================================
# 核心：类型包含内容，不是指令操作数据
# 容器 = 类型，内容 = 类型的实例
# 高维容器 = 范畴，串联 = 态射
# ============================================
# 造字原理类比：
# - 偏旁部首 = 范畴（类型）
# - 笔画 = 态射（类型之间的关系）
# - 声母韵母 = 范畴的索引
# - 不是少数编码统治所有，而是每个容器有自己的范畴
# ============================================

type
  # ============================================
  # 第一层：零维点 = 最基础的范畴元素
  # ============================================
  # 零维点 = 公约数 = 不可分的最小单元
  # 不增长一维线的长度
  # 一次性机会：一个点就是它本身

  零维点* = object
    字符*: string      # Unicode字符
    码位*: uint8      # 0-63码位
    拼音*: string      # 自定义发音

  # ============================================
  # 第二层：一维线 = 零维点的串联
  # ============================================
  # 一维线 = 时间 = 零维点的有序排列
  # 线不增长点的数量，只串联点
  # 线性时间 = 点A → 点B → 点C

  一维线* = object
    点序列*: seq[零维点]  # 零维点的串联
    长度*: int           # 点数量（不是线长度）

  # ============================================
  # 第三层：二维面 = 一维线的并集
  # ============================================
  # 二维面 = 并集 = 多条一维线的并排
  # 面 = 线1 ∪ 线2 ∪ 线3
  # 斜线进位 = 对角线填充

  二维面* = object
    线序列*: seq[一维线]  # 一维线的并集
    宽度*: int             # 线数量
    高度*: int             # 单线长度

  # ============================================
  # 第四层：三维体 = 二维面的容器
  # ============================================
  # 三维体 = 容器 = 包含二维面的空间
  # 体 = 面1 × 面2 × 面3
  # 容器有自己的编码系统，不被外部编码统治

  三维体* = object
    面序列*: seq[二维面]   # 二维面的序列
    名称*: string          # 容器名称（自己的范畴）
    编码体系*: string      # 该容器用什么编码
    容量*: int             # 包含多少个面

  # ============================================
  # 第五层：范畴（更高维度的容器）
  # ============================================
  # 范畴 = 高维容器 + 态射
  # 态射 = 范畴之间的关系
  # 不是少数编码统治所有，而是范畴串联范畴

  范畴对象* = object
    内容类型*: string          # 这个范畴包含什么类型
    内容*: seq[零维点 | 一维线 | 二维面 | 三维体]  # 包容万象
    态射表*: seq[态射]         # 这个范畴和其他范畴的关系
    维度*: int                 # 范畴的维度

  # 态射 = 范畴之间的关系
  # 态射f: A → B 表示范畴A到范畴B的变换
  态射* = object
    名称*: string
    源范畴*: string   # A
    目标范畴*: string # B
    变换规则*: string # 怎么变

  # ============================================
  # 第六层：范畴论核心类型
  # ============================================
  # 函子 = 范畴之间的映射
  # 自然变换 = 函子之间的关系
  # 单子 = 自函子的自同态+单位+结合律

  函子* = object
    源*: string
    目标*: string
    对象映射*: proc(x: string): string
    态射映射*: proc(f: 态射): 态射

  单子* = object
    值*: string
    单位*: proc(x: string): 单子   # return
    绑定*: proc(m: 单子, f: proc(x: string): 单子): 单子  # >>=

  # ============================================
  # 第七层：造字范畴（类比偏旁部首）
  # ============================================
  # 偏旁部首 = 范畴（类型）
  # 笔画 = 态射（类型之间的关系）
  # 声母 = 范畴的索引A
  # 韵母 = 范畴的索引B

  偏旁范畴* = object
    偏旁名称*: string        # 如：单人旁、绞丝旁
    包含字符*: seq[零维点]   # 这个偏旁能组哪些字
    语义范畴*: string         # 如：与人相关、与丝相关

  笔画态射* = object
    笔画名称*: string   # 横、竖、撇、捺
    起笔*: (int, int)   # 起点坐标
    终笔*: (int, int)   # 终点坐标
    方向*: int          # 0-7方向

  拼音范畴* = object
    声母*: string       # 如：zh, ch, sh
    韵母*: string       # 如：ang, eng, ing
    声调*: uint8        # 1-4
    包含汉字*: seq[string]

# ============================================
# 核心操作：范畴的串联（态射合成）
# ============================================

proc 串联*(a, b: 一维线): 一维线 =
  # 一维线 + 一维线 = 更长的一维线
  result.点序列 = a.点序列 & b.点序列
  result.长度 = a.长度 + b.长度

proc 并集*(a, b: 二维面): 二维面 =
  # 二维面 + 二维面 = 更宽的二维面
  result.线序列 = a.线序列 & b.线序列
  result.宽度 = a.宽度 + b.宽度
  result.高度 = max(a.高度, b.高度)

proc 包含*(容器: 三维体, 内容: 二维面): bool =
  # 检查内容是否在该容器的范畴内
  for 面 in 容器.面序列:
    if 面.宽度 == 内容.宽度 and 面.高度 == 内容.高度:
      return true
  result = false

proc 态射合成*(f, g: 态射): 态射 =
  # 态射合成：f: A→B, g: B→C, 则 g∘f: A→C
  if f.目标范畴 == g.源范畴:
    result.名称 = f.名称 & "∘" & g.名称
    result.源范畴 = f.源范畴
    result.目标范畴 = g.目标范畴
    result.变换规则 = "合成(" & f.变换规则 & ", " & g.变换规则 & ")"

proc 范畴串联*(容器A, 容器B: 三维体, 态射f: 态射): 三维体 =
  # 高维容器串联：高维 = 更高维度的范畴
  result.名称 = 容器A.名称 & "∘" & 容器B.名称
  result.面序列 = 容器A.面序列 & 容器B.面序列
  result.编码体系 = "复合编码:" & 容器A.编码体系 & "+" & 容器B.编码体系
  result.容量 = 容器A.容量 + 容器B.容量

# ============================================
# 造字范畴演示
# ============================================

proc 创建偏旁范畴*(名称: string, 语义: string): 偏旁范畴 =
  result.偏旁名称 = 名称
  result.语义范畴 = 语义
  result.包含字符 = @[]

proc 添加字符*(范畴: var 偏旁范畴, 字符: 零维点) =
  范畴.包含字符.add(字符)

proc 笔画合成*(笔画1, 笔画2: 笔画态射): 笔画态射 =
  # 笔画 + 笔画 = 新笔画
  result.笔画名称 = 笔画1.笔画名称 & "+" & 笔画2.笔画名称
  result.起笔 = 笔画1.起笔
  result.终笔 = 笔画2.终笔

# ============================================
# 单子演示（Maybe单子 = 有值或无值）
# ============================================

proc 返回单子*(x: string): 单子 =
  result.值 = x

proc 绑定单子*(m: 单子, f: proc(x: string): 单子): 单子 =
  if m.值 == "":
    result.值 = ""  # Nothing
  else:
    result = f(m.值)

proc 是空*(m: 单子): bool =
  result = m.值 == ""

# ============================================
# 演示入口
# ============================================

when isMainModule:
  echo "========== 南囡囝范畴论编码系统 v0.1 =========="
  echo "类型包含内容，不是指令操作数据"
  echo ""

  echo "--- 零维点 ---"
  let 点A = 零维点(字符: "囡", 码位: 10, 拼音: "nan")
  let 点B = 零维点(字符: "囝", 码位: 11, 拼音: "nan")
  echo "点A: " & 点A.字符 & " 码位=" & $点A.码位 & " 拼音=" & 点A.拼音
  echo "点B: " & 点B.字符 & " 码位=" & $点B.码位 & " 拼音=" & 点B.拼音

  echo ""
  echo "--- 一维线串联 ---"
  var 线1 = 一维线(点序列: @[点A, 点B], 长度: 2)
  echo "线1: " & $线1.点序列.len & "个点"
  var 线2 = 一维线(点序列: @[点A], 长度: 1)
  let 线合成 = 串联(线1, 线2)
  echo "线1+线2串联后: " & $线合成.点序列.len & "个点"

  echo ""
  echo "--- 二维面并集 ---"
  var 面1 = 二维面(线序列: @[线1, 线2], 宽度: 2, 高度: 2)
  var 面2 = 二维面(线序列: @[线1], 宽度: 1, 高度: 2)
  let 面并 = 并集(面1, 面2)
  echo "面1∪面2并集后: " & $面并.线序列.len & "条线"

  echo ""
  echo "--- 三维体（容器）---"
  var 容器 = 三维体(
    面序列: @[面1, 面2],
    名称: "南囡囝容器",
    编码体系: "零维64进制",
    容量: 2
  )
  echo "容器: " & 容器.名称
  echo "  编码体系: " & 容器.编码体系
  echo "  包含面数: " & $容器.容量

  echo ""
  echo "--- 态射合成 ---"
  var 态射1 = 态射(名称: "f", 源范畴: "A", 目标范畴: "B", 变换规则: "×2")
  var 态射2 = 态射(名称: "g", 源范畴: "B", 目标范畴: "C", 变换规则: "+1")
  let 合成态射 = 态射合成(态射1, 态射2)
  echo "f: " & 态射1.源范畴 & "→" & 态射1.目标范畴
  echo "g: " & 态射2.源范畴 & "→" & 态射2.目标范畴
  echo "g∘f: " & 合成态射.源范畴 & "→" & 合成态射.目标范畴

  echo ""
  echo "--- 范畴串联（高维）---"
  let 高维容器 = 范畴串联(容器, 容器, 态射1)
  echo "高维容器: " & 高维容器.名称
  echo "  编码体系: " & 高维容器.编码体系
  echo "  容量: " & $高维容器.容量

  echo ""
  echo "--- 偏旁范畴（造字）---"
  var 单人旁 = 创建偏旁范畴("单人旁", "与人相关")
  echo "偏旁: " & 单人旁.偏旁名称 & " → 语义范畴: " & 单人旁.语义范畴

  echo ""
  echo "--- 笔画态射 ---"
  var 横 = 笔画态射(笔画名称: "横", 起笔: (0,0), 终笔: (10,0), 方向: 0)
  var 竖 = 笔画态射(笔画名称: "竖", 起笔: (5,0), 终笔: (5,10), 方向: 2)
  echo "横: " & 横.笔画名称 & " " & $横.起笔 & "→" & $横.终笔
  echo "竖: " & 竖.笔画名称 & " " & $竖.起笔 & "→" & $竖.终笔
  let 横竖 = 笔画合成(横, 竖)
  echo "横+竖: " & 横竖.笔画名称

  echo ""
  echo "--- 单子（Maybe）---"
  let 有值 = 返回单子("hello")
  let 无值 = 单子(值: "")
  echo "Just: " & 有值.值 & " 是空?" & $是空(有值)
  echo "Nothing: " & (if 无值.值 == "": "空" else: 无值.值) & " 是空?" & $是空(无值)

  echo ""
  echo "========== 范畴论 v0.1 演示完毕 =========="
  echo "类型包含内容，范畴串联范畴"
