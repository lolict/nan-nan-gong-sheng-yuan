## 六、零维符号体系核心原则

1. **点存在容器里**：100个点在一个容器，用完换容器，线长度不变
2. **预加载索引**：运行前把符号全加载好，运行时只查表不生成
3. **O(1)查表**：给定坐标直接计算偏移，不用搜索
4. **容器进制**：64×64×64 = 262144个码位，三维坐标压缩成一维
5. **不增长线长度**：换容器不拉长符号串

## 七、AI撞墙点（必须自检）

1. AI只会用十进制/十六进制/ASCII/Unicode这些系统给的秩序种子
2. 不知道用韵母/声母/偏旁自己长秩序
3. 韵母容器只有37个符号（不是7个），声母23个，不需要匹配
4. 必须跨容器取物（从声母容器拿声母训练韵母容器）
5. 训练必须遍历0维→1维全部阀门，不能只做一半

