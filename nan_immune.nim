when isMainModule:
  echo "========== 负样本免疫库 v0.1 =========="
  echo ""

  # 1. 创建记忆库
  var 记忆库 = 新建记忆库("南囡囝免疫系统")

  echo "--- 创建免疫记忆库 ---"
  echo "名称: " & 记忆库.名称
  echo "状态: 空库，待收录负样本"
  echo ""

  # 2. 识别并入库几个典型负样本
  echo "--- 识别负样本 ---"

  # 负样本1：韵母容器被错误声母入侵
  var 样本1 = 记忆库.识别负样本(
    "错误声母_x",
    99'u8,
    "该声母不包含在任何已知声母集合中",
    "韵母容器",
    "韵母公约数",
    @["x", "未知声母", "越界码位"],
    2
  )
  记忆库.负样本入库(样本1)
  echo "  收录: " & 样本1.标识 & " 原因: " & 样本1.排斥原因

  # 负样本2：十六进制编码入侵产权流
  var 样本2 = 记忆库.识别负样本(
    "HEX编码_0x",
    100'u8,
    "十六进制编码不是本系统的发音位置",
    "产权容器",
    "产权公约数",
    @["0x", "hex", "ABCDEF"],
    4
  )
  记忆库.负样本入库(样本2)
  echo "  收录: " & 样本2.标识 & " 原因: " & 样本2.排斥原因

  # 负样本3：gcc依赖入侵零依赖体系
  var 样本3 = 记忆库.识别负样本(
    "gcc依赖",
    101'u8,
    "gcc是外部依赖，违反零外部依赖原则",
    "南囡囝容器",
    "零依赖公约数",
    @["gcc", "glibc", "-lm"],
    5
  )
  记忆库.负样本入库(样本3)
  echo "  收录: " & 样本3.标识 & " 原因: " & 样本3.排斥原因

  echo ""

  # 3. 判定免疫响应
  echo "--- 免疫响应判定 ---"
  for 样本 in 记忆库.记忆条目:
    let 响应 = 判定免疫响应(样本)
    echo "  " & 样本.标识 & " → " & 响应.响应类型 &
         " (强度" & $响应.响应强度 & ")"
    if 响应.是否记忆:
      echo "    → 记忆入库"
    echo "    → 回写: " & 响应.回写内容

  echo ""

  # 4. 回写协议广播
  echo "--- 回写协议广播 ---"
  let 相关容器 = @["韵母容器", "声母容器", "偏旁容器", "产权容器"]
  discard 广播回写(记忆库, 样本2, 相关容器)

  echo ""

  # 5. 快速匹配演示
  echo "--- 快速特征匹配 ---"
  let (命中1, id1, 次数1) = 快速匹配(记忆库, @["x", "未知声母"])
  echo "  检测特征[@x, 未知声母] → " &
       (if 命中1: "命中! 样本ID:" & $id1 & " 接触次数:" & $次数1
                 else: "无匹配")

  let (命中2, id2, 次数2) = 快速匹配(记忆库, @["zig", "build"])
  echo "  检测特征[@zig, build] → " &
       (if 命中2: "命中! 样本ID:" & $id2 & " 接触次数:" & $次数2
                 else: "无匹配（不在记忆中）")

  echo ""

  # 6. 侵权判定
  echo "--- 产权流侵权判定 ---"
  let (侵权1, 原因1) = 产权流侵权判定(0, 100, 记忆库, "")
  echo "  产权(0, 100) → " & (if 侵权1: "侵权: " & 原因1 else: "无侵权")

  let (侵权2, 原因2) = 产权流侵权判定(50, 50, 记忆库, "HEX编码_0x")
  echo "  产权(50, 50) + HEX编码 → " &
       (if 侵权2: "侵权: " & 原因2 else: "无侵权")

  echo ""

  # 7. 容器免疫状态
  echo "--- 容器免疫状态 ---"
  var 韵母免疫 = 新建容器免疫状态("韵母容器", "韵母公约数")
  echo "  初始: " & 韵母免疫.容器名称 &
       " 免疫强度:" & $韵母免疫.免疫强度 &
       " 已感染:" & (if 韵母免疫.已被感染: "是" else: "否")
  韵母免疫.感染更新(样本1)
  echo "  更新后: " & 韵母免疫.容器名称 &
       " 免疫强度:" & $韵母免疫.免疫强度 &
       " 隔离数:" & $韵母免疫.免疫记忆数

  echo ""
  echo "========== 负样本免疫库 v0.1 完毕 =========="
  echo "核心: 公约数不在其中 = 负样本 → 记忆库 + 回写协议"
