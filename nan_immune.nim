# 南囡囝负样本免疫库 v0.1
# ============================================
# 免疫系统 = 识别并排斥公约数不在其中的容器
# 记忆库 = 记录所有被排斥过的负样本，形成免疫记忆
# 回写协议 = 新负样本入库时，通知相关容器更新边界
#
# 类比：
# 公约数 = 身体（自己的DNA）
# 公倍数 = 免疫细胞（识别自我/非我）
# 负样本 = 抗原/病毒（被排斥）
# 记忆库 = 免疫记忆（再次遇到同类抗原时快速响应）
# ============================================

type
  # ============================================
  # 负样本 = 被公约数排斥的容器
  # 公约数不在其中 = 非我 = 负样本
  # ============================================
  负样本* = object
    标识*: string              # 负样本的唯一名称
    码位*: uint8               # 在64码位表中的位置
    入侵时间*: string          # 被识别为负样本的时间
    排斥原因*: string          # 为什么被排斥
    伤害等级*: uint8           # 1-5，伤害程度
    宿主容器*: string          # 它试图入侵哪个容器
    宿主公约数*: string        # 该容器的公约数（被入侵的目标）
    特征指纹*: seq[string]     # 负样本的特征，用于识别同类
    接触次数*: int             # 遇到它的次数
    首次接触时间*: string
    最近接触时间*: string

  # ============================================
  # 免疫记忆库 = 所有负样本的记录
  # 免疫系统用这份记录快速判断"这是不是负样本"
  # ============================================
  免疫记忆库* = object
    名称*: string
    创建时间*: string
    总收录*: int               # 收录的负样本总数
    活跃负样本*: int           # 当前仍然活跃的负样本数
    记忆条目*: seq[负样本]     # 所有记忆
    特征索引*: seq[(string, seq[int])]  # (特征指纹, 匹配的负样本ID列表)

  # ============================================
  # 免疫响应 = 遇到负样本时的响应行为
  # ============================================
  免疫响应* = object
    响应类型*: string          # "排斥"/"隔离"/"吞噬"/"记忆"
    响应强度*: uint8           # 1-5
    是否记忆*: bool            # 是否加入记忆库
    回写目标*: seq[string]     # 需要通知更新的容器列表
    回写内容*: string          # 回写什么内容

  # ============================================
  # 回写协议 = 负样本入库后通知相关容器
  # ============================================
  回写协议* = object
    发起容器*: string          # 谁发起的回写
    目标容器*: string          # 通知谁
    回写类型*: string          # "新增负样本"/"更新边界"/"隔离通知"
    内容*: string              # 具体内容
    时间戳*: string
    状态*: string              # "待回写"/"回写中"/"已完成"/"失败"

  # ============================================
  # 容器免疫状态 = 每个容器的免疫能力
  # ============================================
  容器免疫状态* = object
    容器名称*: string
    公约数*: string            # 该容器的公约数
    已被感染*: bool            # 是否被负样本入侵过
    免疫记忆数*: int           # 该容器记忆了多少负样本
    隔离名单*: seq[string]     # 被隔离的负样本列表
    免疫强度*: uint8           # 1-5，免疫强度

# ============================================
# 创建空记忆库
# ============================================

proc 新建记忆库*(名称: string): 免疫记忆库 =
  result.名称 = 名称
  result.创建时间 = "2026-08-23"
  result.总收录 = 0
  result.活跃负样本 = 0
  result.记忆条目 = @[]
  result.特征索引 = @[]

# ============================================
# 识别负样本
# 公约数不在其中 → 负样本
# ============================================

proc 是负样本*(容器公约数: string, 检测对象特征: seq[string]): bool =
  # 如果检测对象的特征与公约数无关，则为负样本
  for 特征 in 检测对象特征:
    if 特征 == 容器公约数:
      return false  # 包含公约数，不是负样本
  return true       # 不包含公约数，是负样本

proc 识别负样本*(记忆库: var 免疫记忆库,
                 标识: string,
                 码位: uint8,
                 排斥原因: string,
                 宿主容器: string,
                 宿主公约数: string,
                 特征指纹: seq[string],
                 伤害等级: uint8 = 3): 负样本 =

  result.标识 = 标识
  result.码位 = 码位
  result.排斥原因 = 排斥原因
  result.宿主容器 = 宿主容器
  result.宿主公约数 = 宿主公约数
  result.特征指纹 = 特征指纹
  result.伤害等级 = 伤害等级
  result.入侵时间 = "2026-08-23"
  result.接触次数 = 1
  result.首次接触时间 = "2026-08-23"
  result.最近接触时间 = "2026-08-23"

# ============================================
# 负样本入库 + 特征索引
# ============================================

proc 负样本入库*(记忆库: var 免疫记忆库, 样本: 负样本) =
  # 1. 加入记忆
  记忆库.记忆条目.add(样本)
  记忆库.总收录 += 1
  记忆库.活跃负样本 += 1

  # 2. 更新特征索引
  for 特征 in 样本.特征指纹:
    # 查找是否已有该特征的索引
    var 已有 = false
    for i, 索引 in 记忆库.特征索引:
      if 索引[0] == 特征:
        记忆库.特征索引[i][1].add(记忆库.记忆条目.high)
        已有 = true
        break
    if not 已有:
      记忆库.特征索引.add((特征, @[记忆库.记忆条目.high]))

proc 接触更新*(记忆库: var 免疫记忆库, 样本ID: int) =
  # 已有负样本再次接触，更新接触次数
  if 样本ID >= 0 and 样本ID < 记忆库.记忆条目.len:
    记忆库.记忆条目[样本ID].接触次数 += 1
    记忆库.记忆条目[样本ID].最近接触时间 = "2026-08-23"

# ============================================
# 回写协议
# 新负样本入库后，通知所有相关容器更新边界
# ============================================

proc 新建回写协议*(发起容器, 目标容器, 回写类型, 内容: string): 回写协议 =
  result.发起容器 = 发起容器
  result.目标容器 = 目标容器
  result.回写类型 = 回写类型
  result.内容 = 内容
  result.时间戳 = "2026-08-23"
  result.状态 = "待回写"

proc 执行回写*(协议: var 回写协议): bool =
  # 模拟回写执行
  case 协议.回写类型
  of "新增负样本":
    echo "  回写[" & 协议.目标容器 & "]: 发现新负样本，更新隔离名单"
    echo "  内容: " & 协议.内容
    协议.状态 = "已完成"
    return true
  of "更新边界":
    echo "  回写[" & 协议.目标容器 & "]: 公约数边界被负样本侵入，收缩边界"
    echo "  内容: " & 协议.内容
    协议.状态 = "已完成"
    return true
  of "隔离通知":
    echo "  回写[" & 协议.目标容器 & "]: 该容器已被隔离，禁止接收外部输入"
    echo "  内容: " & 协议.内容
    协议.状态 = "已完成"
    return true
  else:
    协议.状态 = "失败"
    return false

proc 广播回写*(记忆库: 免疫记忆库, 新样本: 负样本, 相关容器: seq[string]): seq[回写协议] =
  # 新负样本入库后，广播给所有相关容器
  result = @[]
  for 容器 in 相关容器:
    if 容器 == 新样本.宿主容器:
      # 宿主容器收到隔离通知
      var 协议 = 新建回写协议(
        "免疫记忆库",
        容器,
        "隔离通知",
        "负样本[" & 新样本.标识 & "]已被隔离，禁止其进入"
      )
      discard 协议.执行回写()
      result.add(协议)
    else:
      # 其他相关容器收到边界更新
      var 协议 = 新建回写协议(
        "免疫记忆库",
        容器,
        "更新边界",
        "检测到负样本[" & 新样本.标识 & "]，特征: " & 新样本.特征指纹.join(", ")
      )
      discard 协议.执行回写()
      result.add(协议)

# ============================================
# 免疫响应判定
# ============================================

proc 判定免疫响应*(样本: 负样本): 免疫响应 =
  result.是否记忆 = true  # 默认记忆

  case 样本.伤害等级
  of 1:
    result.响应类型 = "排斥"
    result.响应强度 = 1
    result.回写目标 = @[样本.宿主容器]
    result.回写内容 = "轻微排斥，不入库"
    result.是否记忆 = false
  of 2:
    result.响应类型 = "排斥"
    result.响应强度 = 2
    result.回写目标 = @[样本.宿主容器]
    result.回写内容 = "中等排斥，加入隔离名单"
  of 3:
    result.响应类型 = "隔离"
    result.响应强度 = 3
    result.回写目标 = @[样本.宿主容器]
    result.回写内容 = "强制隔离，启动免疫记忆"
  of 4:
    result.响应类型 = "吞噬"
    result.响应强度 = 4
    result.回写目标 = @[样本.宿主容器]
    result.回写内容 = "高危吞噬，销毁负样本特征"
  of 5:
    result.响应类型 = "吞噬"
    result.响应强度 = 5
    result.回写目标 = @[]  # 全域广播
    result.回写内容 = "最高危，全域隔离，记忆库全量更新"
  else:
    result.响应类型 = "排斥"
    result.响应强度 = 1

# ============================================
# 快速匹配：给定特征，快速查找是否命中已知负样本
# ============================================

proc 快速匹配*(记忆库: 免疫记忆库, 检测特征: seq[string]): tuple[命中: bool, 样本ID: int, 接触次数: int] =
  # 遍历检测特征的每个特征，查找匹配
  for 特征 in 检测特征:
    for 索引 in 记忆库.特征索引:
      if 索引[0] == 特征:
        # 找到匹配，返回第一个匹配的负样本
        let 样本ID = 索引[1][0]
        if 样本ID < 记忆库.记忆条目.len:
          return (true, 样本ID, 记忆库.记忆条目[样本ID].接触次数)

  return (false, -1, 0)

# ============================================
# 容器免疫状态更新
# ============================================

proc 新建容器免疫状态*(容器名称, 公约数: string): 容器免疫状态 =
  result.容器名称 = 容器名称
  result.公约数 = 公约数
  result.已被感染 = false
  result.免疫记忆数 = 0
  result.隔离名单 = @[]
  result.免疫强度 = 3  # 默认中等

proc 感染更新*(状态: var 容器免疫状态, 样本: 负样本) =
  状态.已被感染 = true
  状态.隔离名单.add(样本.标识)
  状态.免疫记忆数 += 1
  if 样本.伤害等级 >= 4:
    状态.免疫强度 = 5  # 高危感染后免疫强度提升

proc 隔离检测*(状态: 容器免疫状态, 样本标识: string): bool =
  for 名 in 状态.隔离名单:
    if 名 == 样本标识:
      return true
  return false

# ============================================
# 侵权判定（产权流 × 负样本）
# vA + vB == 2 * v_core → 侵权
# ============================================

proc 产权流侵权判定*(产权值A, 产权值B: int, 记忆库: 免疫记忆库, 样本标识: string): tuple[侵权: bool, 原因: string] =
  let 核心产权 = (产权值A + 产权值B) div 2

  # 检查是否有对应的负样本记录
  for 样本 in 记忆库.记忆条目:
    if 样本.标识 == 样本标识:
      # 有记录的负样本参与产权流
      if 样本.伤害等级 >= 3:
        return (true, "负样本[" & 样本标识 & "]参与产权混合，伤害等级" & $样本.伤害等级 & "，判定侵权")
      else:
        return (false, "负样本[" & 样本标识 & "]参与产权混合，伤害等级<3，轻微排斥")

  # 无记录但产权值异常
  if 产权值A == 0 or 产权值B == 0:
    return (true, "产权值为零，公约数不在其中，判定为负样本侵权")
  if 产权值A == 产权值B and 产权值A == 核心产权:
    return (true, "vA + vB == 2 * v_core，完美平均，疑似负样本主导")

  return (false, "无侵权迹象")

