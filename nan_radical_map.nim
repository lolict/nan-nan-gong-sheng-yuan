proc 查字*(图: 部首星图, 名字: string): 恒星 =
  for h in 图.恒星总表:
    if h.名字 == 名字:
      return h
  result.名字 = ""

proc 按声母查*(图: 部首星图, 声母: string): seq[恒星] =
  result = @[]
  for h in 图.恒星总表:
    if h.声母 == 声母:
      result.add(h)

proc 按韵母查*(图: 部首星图, 韵母: string): seq[恒星] =
  result = @[]
  for h in 图.恒星总表:
    if h.韵母 == 韵母:
      result.add(h)

proc 星域统计*(图: 部首星图): string =
  result = ""
  for 星域 in 图.星域表:
    result &= 星域.名字 & "部(" & 星域.符号 & "): " &
              $星域.星等 & "颗星 | "
  result &= "总计: " & $图.恒星总表.len & "颗星"

