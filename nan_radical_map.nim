# ============================================
# 拼音分解
# ============================================

proc 拼音分解*(拼音: string): (string, string, uint8) =
  var 纯拼音 = 拼音
  var 声调: uint8 = 0
  for c in 纯拼音:
    case c
    of 'ā', 'ē', 'ī', 'ō', 'ū', 'ǖ': 声调 = 1
    of 'á', 'é', 'í', 'ó', 'ú', 'ǘ': 声调 = 2
    of 'ǎ', 'ě', 'ǐ', 'ǒ', 'ǔ', 'ǚ': 声调 = 3
    of 'à', 'è', 'ì', 'ò', 'ù', 'ǜ': 声调 = 4
    else: discard

  var 去声调 = ""
  for c in 纯拼音:
    case c
    of 'ā', 'á', 'ǎ', 'à': 去声调.add('a')
    of 'ē', 'é', 'ě', 'è': 去声调.add('e')
    of 'ī', 'í', 'ǐ', 'ì': 去声调.add('i')
    of 'ō', 'ó', 'ǒ', 'ò': 去声调.add('o')
    of 'ū', 'ú', 'ǔ', 'ù': 去声调.add('u')
    of 'ǖ', 'ǘ', 'ǚ', 'ǜ': 去声调.add('v')
    else: 去声调.add(c)

  var 声母 = ""
  for s in 声母集:
    if 去声调.startsWith(s):
      声母 = s
      break
  let 韵母 = if 声母.len > 0: 去声调[声母.len..^1] else: 去声调

  return (声母, 韵母, 声调)

# ============================================
# 新建恒星（汉字）
# ============================================

proc 新建恒星*(名字, 光谱, 语义, 来源0, 来源1: string,
               归属: string): 恒星 =
  result.名字 = 名字
  result.光谱 = 光谱
  result.语义 = 语义
  result.来源 = @[来源0]
  if 来源1.len > 0: result.来源.add(来源1)
  result.归属星域 = 归属

  let (声母, 韵母, 声调) = 拼音分解(光谱)
  result.声母 = 声母
  result.韵母 = 韵母
  result.声调 = 声调

  # 质量 = 笔画数（估算）
  result.质量 = 名字.len * 2  # 占位

# ============================================
# 新建星域（部首）
# ============================================

proc 新建星域*(名字, 符号, 语义域: string): 星域 =
  result.名字 = 名字
  result.符号 = 符号
  result.语义域 = 语义域
  result.恒星表 = @[]
  result.入射星 = @[]
  result.发射星 = @[]
  result.星等 = 0

proc 添加恒星*(星域: var 星域, 恒星: 恒星) =
  if 恒星.来源[0] == 星域.名字:
    # 本星域生成的恒星
    星域.恒星表.add(恒星)
  else:
    # 外来恒星进入
    星域.入射星.add(恒星)

proc 添加发射*(星域: var 星域, 恒星: 恒星, 目标星域: string) =
  if 恒星.来源[0] == 星域.名字:
    星域.发射星.add(恒星)

