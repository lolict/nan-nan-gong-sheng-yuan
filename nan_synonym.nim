proc 有备无患度量*(容器: 近义词容器): string =
  ## 度量这个近义词容器的"有备无患"程度
  ## 活跃投影越多，有备无患程度越高
  let 总数 = 容器.公约数.投影总数
  let 活跃数 = 容器.公约数.活跃投影数
  let 比率 = if 总数 > 0: (活跃数.float / 总数.float * 100).int else: 0

  result = "公约数[" & 容器.公约数.标识 & "]: "
  result &= $活跃数 & "/" & $总数 & " 投影可用 (" & $比率 & "%)"
  if 活跃数 >= 3:
    result &= " ← 充足备份，有备无患"
  elif 活跃数 >= 1:
    result &= " ← 基本可用，建议补充近义词"
  else:
    result &= " ← 危险！所有投影不可用"

