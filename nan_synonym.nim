# 南囡囝近义词容器 v0.1
# ============================================
# 近义词 = 同一公约数在不同维度上的投影
# 有备无患 = 同一公约数下多个可用投影的总集合
# 碗/锅/罐/坛/缸 → 同一"盛器"公约数，不同材质/用途/容积
# 取/拿/获 → 同一"得到"公约数，不同动作方向/力度
#
# 核心规律：
# 近义词不是冗余，是备份
# 近义词不是乱来，是精心筛选的备选投影
# 每个近义词有自己的边界和容积
# 当一种投影不可用时，同公约数下还有其他投影可用
#
# 锅与菜：
# 锅 = 固定层（编译一次，永久不变）
# 菜 = 可变层（运行时加载，随时可换）
# 锅烧好了，菜随时可以换
#
# 产权归属 vs 移动：
# 拿 = 得到（移动），不等于归属（产权）
# 产权链 ≠ 容器链
# ============================================

type
  # ============================================
  # 公约数：不变的身份锚点
  # 所有近义词都指向同一个公约数
  # ============================================
  公约数* = object
    标识*: string           # 公约数的唯一身份
    核心语义*: string       # 这个公约数"是什么"
    维度*: string           # 属于哪个维度（器物/动作/状态/声音...）
    投影总数*: int          # 有多少个近义词投影
    活跃投影数*: int        # 当前可用的近义词数量

  # ============================================
  # 近义投影：公约数在某个维度上的具体呈现
  # 碗 = "盛器"公约数在"陶瓷/饮食/小型"上的投影
  # 锅 = "盛器"公约数在"金属/烹饪/中型"上的投影
  # ============================================
  近义投影* = object
    符号*: string           # 这个投影的字形/名称
    声母*: string           # 发音位置（声母）
    韵母*: string           # 发音位置（韵母）
    声调*: uint8            # 1-4
    材质*: string           # 什么做的（陶瓷/金属/竹木/玻璃...）
    用途*: string           # 用来干什么
    容积等级*: string       # "微小"/"小"/"中"/"大"/"巨"
    边界*: string           # 这个投影的适用边界（什么时候用它）
    远近*: string           # "近义"（高度重叠）/"远亲"（部分重叠）
    状态*: string           # "活跃"/"休眠"/"废弃"

  # ============================================
  # 近义词容器：同一公约数的所有投影
  # ============================================
  近义词容器* = object
    公约数*: 公约数
    投影表*: seq[近义投影]
    当前首选*: string       # 当前语境下的首选投影
    备选队列*: seq[string]  # 首选不可用时的后备顺序

  # ============================================
  # 锅菜分层：固定层 vs 可变层
  # ============================================
  锅层* = object            # 固定层：编译一次，永久不变
    名称*: string
    内容*: seq[string]      # 加载器、解析器、执行器
    锁定*: bool             # 锅一旦烧好就不换
    编译时刻*: string

  菜层* = object            # 可变层：运行时加载，随时可换
    名称*: string
    内容*: seq[string]      # 偏旁表、声母表、韵母表、近义词表
    来源*: string           # 从哪里加载（文本文件/运行时注入）
    热替换*: bool           # 是否支持运行时替换

  # ============================================
  # 产权归属 vs 移动
  # 拿 = 得到（位置变化），不等于归属（所有权变化）
  # ============================================
  产权状态* = object
    归属者*: string         # 这个东西属于谁
    来源*: string           # 归属权的来源（自造/受让/继承...）
    归属时刻*: string       # 何时确立归属
    可转移*: bool           # 是否可以转移给他人
    不可剥夺*: bool         # 是否不可被他人剥夺

  移动记录* = object
    物品*: string           # 被移动的东西
    源容器*: string         # 从哪里来
    目标容器*: string       # 到哪里去
    移动时刻*: string       # 何时移动
    是否携带归属*: bool     # 移动时是否同时转移归属权

  产权链* = object          # 记录"东西是谁的"
    条目表*: seq[产权状态]

  容器链* = object          # 记录"东西在哪里"
    移动记录表*: seq[移动记录]

# ============================================
# 构建公约数
# ============================================

proc 创建公约数*(标识: string, 核心语义: string, 维度: string): 公约数 =
  result.标识 = 标识
  result.核心语义 = 核心语义
  result.维度 = 维度
  result.投影总数 = 0
  result.活跃投影数 = 0

# ============================================
# 构建近义投影
# ============================================

proc 创建投影*(符号: string, 声母: string, 韵母: string, 声调: uint8,
               材质: string, 用途: string, 容积等级: string,
               边界: string, 远近: string = "近义"): 近义投影 =
  result.符号 = 符号
  result.声母 = 声母
  result.韵母 = 韵母
  result.声调 = 声调
  result.材质 = 材质
  result.用途 = 用途
  result.容积等级 = 容积等级
  result.边界 = 边界
  result.远近 = 远近
  result.状态 = "活跃"

# ============================================
# 构建近义词容器
# ============================================

proc 创建近义词容器*(公约数: 公约数): 近义词容器 =
  result.公约数 = 公约数
  result.投影表 = @[]
  result.当前首选 = ""
  result.备选队列 = @[]

proc 纳入投影*(容器: var 近义词容器, 投影: 近义投影) =
  ## 将一个投影纳入近义词容器
  ## 这就是"有备无患"——多一个备选投影，就多一层保障
  容器.投影表.add(投影)
  容器.公约数.投影总数 += 1
  if 投影.状态 == "活跃":
    容器.公约数.活跃投影数 += 1
  if 容器.当前首选 == "":
    容器.当前首选 = 投影.符号

proc 首选不可用时切换*(容器: var 近义词容器): string =
  ## 当前首选投影不可用时，自动切换到下一个备选
  ## 这就是"有备无患"的运行时体现
  if 容器.备选队列.len > 0:
    容器.当前首选 = 容器.备选队列[0]
    容器.备选队列.delete(0)
    return 容器.当前首选
  # 备选队列空了，从投影表中找下一个活跃的
  for 投影 in 容器.投影表:
    if 投影.状态 == "活跃" and 投影.符号 != 容器.当前首选:
      容器.当前首选 = 投影.符号
      return 容器.当前首选
  return "无可用投影"

proc 显示近义词容器*(容器: 近义词容器) =
  echo "公约数[" & 容器.公约数.标识 & "] = " & 容器.公约数.核心语义
  echo "  维度: " & 容器.公约数.维度
  echo "  投影总数: " & $容器.公约数.投影总数
  echo "  活跃投影: " & $容器.公约数.活跃投影数
  echo "  当前首选: " & 容器.当前首选
  echo "  --- 投影列表 ---"
  for 投影 in 容器.投影表:
    echo "    [" & 投影.远近 & "] " & 投影.符号 &
         " (" & 投影.声母 & "+" & 投影.韵母 & "=" &
         $投影.声调 & "声)" &
         " | " & 投影.材质 & "/" & 投影.用途 & "/" & 投影.容积等级
    echo "      边界: " & 投影.边界

